        <strong>Salesperson:</strong> Il coûte vingt-deux euros cinquante.<br>
        <strong>Customer:</strong> Parfait, je vais le prendre.<br>
        <strong>Salesperson:</strong> Très bon choix. Suivez-moi à la caisse.<br>
        <strong>Cashier:</strong> Ça fait vingt-deux euros cinquante. Comment souhaitez-vous payer?<br>
        <strong>Customer:</strong> Par carte, s'il vous plaît.<br>
        <strong>Cashier:</strong> Bien sûr. Insérez votre carte et tapez votre code.<br>
        <strong>Customer:</strong> <em>[Completes payment]</em><br>
