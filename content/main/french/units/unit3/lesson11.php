<h2>Useful Phrases</h2>
<ul>
    <li><span class="french-word">Où se trouve...?</span> (oo suh troov) - Where is...?</li>
    <li><span class="french-word">Je cherche...</span> (juh shersh) - I'm looking for...</li>
    <li><span class="french-word">Combien coûte...?</span> (kom-bee-en koot) - How much is...?</li>
    <li><span class="french-word">C'est tout, merci.</span> (say too, mare-see) - That's all, thank you.</li>
</ul>

