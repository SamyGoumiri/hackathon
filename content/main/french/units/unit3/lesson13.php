<h2>Useful Shopping Phrases</h2>
<ul>
    <li><span class="french-word">Je cherche...</span> (zhuh shersh) - I'm looking for...</li>
    <li><span class="french-word">Avez-vous ce/cette... en taille...</span> (ah-vay voo suh/set... ahn tie...) - Do you have this... in size...</li>
    <li><span class="french-word">Je peux l'essayer?</span> (zhuh puh less-ay-yay) - Can I try it on?</li>
    <li><span class="french-word">La cabine d'essayage?</span> (lah kah-been dess-ay-ahzh) - The fitting room?</li>
    <li><span class="french-word">Ça me va bien?</span> (sah muh vah bee-en) - Does it look good on me?</li>
    <li><span class="french-word">C'est trop grand/petit.</span> (say troh grahn/puh-tee) - It's too big/small.</li>
    <li><span class="french-word">Je vais le/la prendre.</span> (zhuh vay luh/lah prahn-druh) - I'll take it.</li>
</ul>

<div class="example">
    <div class="example-title">Example Conversation in a Clothing Store</div>
    <p>
        <strong>Sales Assistant:</strong> Bonjour, je peux vous aider?<br>
        <strong>Customer:</strong> Bonjour, oui, je cherche une chemise blanche.<br>
        <strong>Sales Assistant:</strong> Bien sûr. Quelle est votre taille?<br>
        <strong>Customer:</strong> Je fais du M, généralement.<br>
        <strong>Sales Assistant:</strong> Voici une chemise blanche en taille M. Voulez-vous l'essayer?<br>
        <strong>Customer:</strong> Oui, s'il vous plaît. Où est la cabine d'essayage?<br>
        <strong>Sales Assistant:</strong> Par là, à droite.<br>
        <em>[After trying on]</em><br>
        <strong>Customer:</strong> Je vais la prendre. Elle me va très bien.<br>
        <strong>Sales Assistant:</strong> Parfait! Vous pouvez payer à la caisse.
    </p>
</div>

<p>In France, clothing sizes may differ from what you're used to. French sizes for women's clothing are typically 2 sizes higher than US sizes (e.g., US 6 = French 38). For men, you may need to convert from inches to centimeters for pants. It's always a good idea to try clothes on before buying!</p>
