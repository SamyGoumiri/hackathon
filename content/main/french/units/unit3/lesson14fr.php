<h2>Talking About Prices</h2>
<ul>
    <li><span class="french-word">C'est combien?</span> (say kom-bee-en) - How much is it?</li>
    <li><span class="french-word">Ça coûte combien?</span> (sah koot kom-bee-en) - How much does it cost?</li>
    <li><span class="french-word">C'est trois euros cinquante.</span> (say twa zuh-roh sank-ahnt) - It's €3.50.</li>
    <li><span class="french-word">C'est cher.</span> (say shair) - It's expensive.</li>
    <li><span class="french-word">C'est bon marché.</span> (say bon mar-shay) - It's inexpensive.</li>
    <li><span class="french-word">C'est en solde.</span> (say tahn sold) - It's on sale.</li>
    <li><span class="french-word">Je peux payer par carte?</span> (jhuh puh pay-ay par kart) - Can I pay by card?</li>
    <li><span class="french-word">Je n'ai pas assez d'argent.</span> (jhuh nay paz ah-say dar-zhahn) - I don't have enough money.</li>
</ul>

<div class="example">
    <div class="example-title">Example Conversation About Money</div>
    <p>
        <strong>Customer:</strong> Bonjour, combien coûte ce pull, s'il vous plaît?<br>
        <strong>Salesperson:</strong> Ce pull coûte quarante-neuf euros quatre-vingt-dix.<br>
        <strong>Customer:</strong> C'est un peu cher. Est-ce qu'il est en solde?<br>
        <strong>Salesperson:</strong> Oui, en fait, c'est déjà le prix soldé. Il coûtait soixante-dix euros avant.<br>
        <strong>Customer:</strong> D'accord, je vais le prendre. Est-ce que je peux payer par carte?<br>
        <strong>Salesperson:</strong> Bien sûr, suivez-moi à la caisse.<br>
        <strong>Cashier:</strong> Ça fait quarante-neuf euros quatre-vingt-dix.<br>
        <strong>Customer:</strong> Voici ma carte.<br>
        <strong>Cashier:</strong> Merci. Tapez votre code, s'il vous plaît.<br>
        <strong>Customer:</strong> Voilà.<br>
        <strong>Cashier:</strong> Merci pour votre achat. Au revoir!<br>
        <strong>Customer:</strong> Merci beaucoup. Au revoir!
    </p>
</div>

<p>In France and other European countries, prices are written with a comma instead of a decimal point. For example, €3.50 would be written as 3,50 €. Also, the euro symbol (€) often comes after the number, not before as with the dollar sign.</p>
