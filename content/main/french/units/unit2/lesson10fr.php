<div class="example">
    <div class="example-title">Example Conversations</div>
    <p>
        <strong>Conversation 1:</strong><br>
        <strong>Person A:</strong> Quel temps fait-il aujourd'hui?<br>
        <strong>Person B:</strong> Il fait beau et chaud. Il fait du soleil et il y a quelques nuages.<br>
        <strong>Person A:</strong> Quelle est la température?<br>
        <strong>Person B:</strong> Il fait 25 degrés.<br>
        <strong>Person A:</strong> C'est parfait pour aller à la plage!
    </p>
    <p>
        <strong>Conversation 2:</strong><br>
        <strong>Person A:</strong> Quel temps fait-il à Paris ce week-end?<br>
        <strong>Person B:</strong> D'après la météo, il va pleuvoir samedi et il fera nuageux dimanche.<br>
        <strong>Person A:</strong> Quelle température fera-t-il?<br>
        <strong>Person B:</strong> Il fera environ 15 degrés. Il fera assez frais.<br>
        <strong>Person A:</strong> Je vais prendre un parapluie et une veste alors.
    </p>
</div>

