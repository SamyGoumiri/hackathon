<h2>Expressing Dates</h2>
<p>In French, dates are typically written and pronounced in the format "le + day number + month".</p>

<table class="vocabulary-table">
    <tr>
        <th>French</th>
        <th>Pronunciation</th>
        <th>English</th>
    </tr>
    <tr>
        <td class="french-word">Quelle est la date aujourd'hui?</td>
        <td class="pronunciation">kel ay la dat oh-zhoor-dwee</td>
        <td>What's the date today?</td>
    </tr>
    <tr>
        <td class="french-word">Aujourd'hui, c'est le...</td>
        <td class="pronunciation">oh-zhoor-dwee say luh</td>
        <td>Today is the...</td>
    </tr>
    <tr>
        <td class="french-word">le premier janvier</td>
        <td class="pronunciation">luh pruh-mee-ay zhahn-vee-ay</td>
        <td>January 1st</td>
    </tr>
    <tr>
        <td class="french-word">le deux février</td>
        <td class="pronunciation">luh duh fay-vree-ay</td>
        <td>February 2nd</td>
    </tr>
    <tr>
        <td class="french-word">le quinze mars</td>
