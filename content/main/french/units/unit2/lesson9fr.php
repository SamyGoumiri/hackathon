<div class="example">
    <div class="example-title">Example Conversation</div>
    <p>
        <strong>Person A:</strong> Quelle est la date aujourd'hui?<br>
        <strong>Person B:</strong> Aujourd'hui, c'est le quinze septembre.<br>
        <strong>Person A:</strong> Et quel jour sommes-nous?<br>
        <strong>Person B:</strong> Nous sommes jeudi.<br>
        <strong>Person A:</strong> Merci. J'ai un rendez-vous lundi prochain, le vingt septembre.<br>
        <strong>Person B:</strong> Non, lundi prochain, c'est le dix-neuf septembre.<br>
        <strong>Person A:</strong> Ah, vous avez raison. Merci!
    </p>
