<h2>Sightseeing Vocabulary</h2>
<ul>
    <li><span class="french-word">faire du tourisme</span> (fair dew too-reezm) - to go sightseeing</li>
    <li><span class="french-word">visiter</span> (vee-zee-tay) - to visit</li>
    <li><span class="french-word">le guide</span> (luh geed) - guide (person or book)</li>
    <li><span class="french-word">la visite guidée</span> (lah vee-zeet gee-day) - guided tour</li>
    <li><span class="french-word">le plan/la carte</span> (luh plan/lah kart) - map</li>
    <li><span class="french-word">les horaires d'ouverture</span> (lay o-rare doo-ver-toor) - opening hours</li>
    <li><span class="french-word">le billet (d'entrée)</span> (luh bee-yay don-tray) - (admission) ticket</li>
    <li><span class="french-word">la vue</span> (lah vew) - view</li>
    <li><span class="french-word">prendre des photos</span> (pron-druh day fo-toh) - to take pictures</li>
</ul>

<h2>Useful Phrases for Sightseeing</h2>
<ul>
    <li><span class="french-word">À quelle heure est-ce que ça ouvre/ferme?</span> (ah kel er es kuh sah oov/ferm) - What time does it open/close?</li>
    <li><span class="french-word">Combien coûte l'entrée?</span> (kom-bee-en koot lon-tray) - How much is the admission?</li>
    <li><span class="french-word">Y a-t-il une réduction pour les étudiants?</span> (ee ah-teel ewn ray-dewk-see-on poor lay zay-tew-dee-on) - Is there a discount for students?</li>
    <li><span class="french-word">Est-ce qu'il y a une visite guidée en anglais?</span> (es keel ee ah ewn vee-zeet gee-day on on-glay) - Is there a guided tour in English?</li>
    <li><span class="french-word">Est-ce que je peux prendre des photos?</span> (es kuh zhuh puh pron-druh day fo-toh) - Can I take pictures?</li>
    <li><span class="french-word">Où sont les toilettes?</span> (oo son lay twa-let) - Where are the restrooms?</li>
</ul>

