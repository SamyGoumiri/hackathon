<h2>Asking for Directions</h2>
<ul>
    <li><span class="french-word">Excusez-moi, où est...?</span> (ex-kew-zay mwah, oo ay) - Excuse me, where is...?</li>
    <li><span class="french-word">Comment aller à...?</span> (ko-mon ah-lay ah) - How do I get to...?</li>
    <li><span class="french-word">Pourriez-vous m'indiquer le chemin pour...?</span> (poo-ree-ay voo man-dee-kay luh shuh-man poor) - Could you show me the way to...?</li>
    <li><span class="french-word">Je cherche...</span> (zhuh shersh) - I'm looking for...</li>
    <li><span class="french-word">Est-ce que c'est loin?</span> (ess kuh say lwan) - Is it far?</li>
    <li><span class="french-word">Combien de temps pour y aller à pied?</span> (kom-bee-en duh ton poor ee ah-lay ah pee-ay) - How long does it take to get there on foot?</li>
</ul>

<h2>Giving Directions</h2>
<ul>
    <li><span class="french-word">Tournez à droite/gauche.</span> (toor-nay ah drwaht/gohsh) - Turn right/left.</li>
    <li><span class="french-word">Allez tout droit.</span> (ah-lay too drwah) - Go straight ahead.</li>
    <li><span class="french-word">Continuez jusqu'à...</span> (kon-tee-new-ay zhew-skah) - Continue until...</li>
    <li><span class="french-word">Prenez la première/deuxième rue à droite/gauche.</span> (pruh-nay lah pruh-mee-air/duh-zee-em roo ah drwaht/gohsh) - Take the first/second street on the right/left.</li>
    <li><span class="french-word">C'est à environ 10 minutes à pied.</span> (say tah on-vee-ron dee mee-newt ah pee-ay) - It's about 10 minutes on foot.</li>
</ul>

<div class="example">
    <div class="example-title">Example Conversation</div>
    <p>
        <strong>Tourist:</strong> Excusez-moi, madame. Où est le musée du Louvre, s'il vous plaît?<br>
        <strong>Local:</strong> Le Louvre? Alors, vous allez tout droit sur cette rue pendant environ 5 minutes. Ensuite, tournez à gauche au carrefour. Continuez tout droit et vous verrez le Louvre à votre droite. C'est un grand bâtiment avec une pyramide de verre.<br>
        <strong>Tourist:</strong> C'est loin d'ici?<br>
        <strong>Local:</strong> Non, à peu près 15 minutes à pied.<br>
        <strong>Tourist:</strong> Merci beaucoup pour votre aide!<br>
        <strong>Local:</strong> Je vous en prie. Bonne journée!
    </p>
</div>

<div class="practice-tip">
    <h3>Practice Tip</h3>
    <p>French people appreciate when you begin your questions with "Excusez-moi" or "Bonjour" before asking for directions. It's considered more polite than directly asking a question.</p>
