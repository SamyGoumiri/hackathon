<h2>Useful Phrases for Travel Problems</h2>

<h3>Transportation Issues</h3>
<ul>
    <li><span class="french-word">Mon train/vol a été retardé/annulé.</span> (mon tran/vol ah ay-tay ruh-tar-day/ah-new-lay) - My train/flight has been delayed/cancelled.</li>
    <li><span class="french-word">J'ai manqué mon train/vol.</span> (zhay mon-kay mon tran/vol) - I missed my train/flight.</li>
    <li><span class="french-word">Quand est le prochain départ?</span> (kon ay luh pro-shan day-par) - When is the next departure?</li>
    <li><span class="french-word">Puis-je être remboursé?</span> (pwee-jhuh etruh ram-boor-say) - Can I get a refund?</li>
</ul>

<h3>Lost Items and Luggage</h3>
<ul>
    <li><span class="french-word">J'ai perdu mes bagages.</span> (zhay pair-dew may bah-gahj) - I've lost my luggage.</li>
    <li><span class="french-word">J'ai perdu mon portefeuille/mon passeport.</span> (zhay pair-dew mon port-fuh-yuh/mon pass-por) - I've lost my wallet/passport.</li>
    <li><span class="french-word">Où est le bureau des objets trouvés?</span> (oo ay luh bew-roh day zob-zhay troo-vay) - Where is the lost and found office?</li>
    <li><span class="french-word">J'ai besoin de faire une déclaration de vol.</span> (zhay buh-zwan duh fair ewn day-klah-rah-see-on duh vol) - I need to file a theft report.</li>
</ul>

<h3>Health Issues</h3>
<ul>
    <li><span class="french-word">Je ne me sens pas bien.</span> (jhuh nuh muh son pah bee-en) - I don't feel well.</li>
    <li><span class="french-word">J'ai besoin d'un médecin.</span> (zhay buh-zwan dun may-duh-san) - I need a doctor.</li>
    <li><span class="french-word">Où est l'hôpital le plus proche?</span> (oo ay lo-pee-tal luh ploo prosh) - Where is the nearest hospital?</li>
    <li><span class="french-word">J'ai une assurance voyage.</span> (zhay ewn ah-sew-ronss voy-ahj) - I have travel insurance.</li>
</ul>

<h3>General Emergency Phrases</h3>
<ul>
    <li><span class="french-word">Au secours!</span> (oh suh-koor) - Help!</li>
    <li><span class="french-word">C'est une urgence!</span> (say tewn oor-zhonss) - It's an emergency!</li>
    <li><span class="french-word">Appelez une ambulance/la police!</span> (ah-pley ewn om-bew-lonss/lah po-leess) - Call an ambulance/the police!</li>
    <li><span class="french-word">J'ai besoin d'aide.</span> (zhay buh-zwan ded) - I need help.</li>
</ul>

<div class="example">
    <div class="example-title">Example Conversation - Lost Luggage</div>
    <p>
        <strong>Traveler:</strong> Excusez-moi, j'ai un problème. Je ne trouve pas ma valise sur le tapis roulant.<br>
        <strong>Airport Staff:</strong> Je suis désolé d'entendre ça. Pouvez-vous me décrire votre valise, s'il vous plaît?<br>
        <strong>Traveler:</strong> C'est une grande valise noire avec une étiquette rouge. Mon nom est écrit dessus.<br>
        <strong>Airport Staff:</strong> D'accord. Vous devez remplir un formulaire de bagages perdus. Avez-vous votre billet d'avion et votre étiquette de bagage?<br>
        <strong>Traveler:</strong> Oui, voici mon billet et l'étiquette.<br>
        <strong>Airport Staff:</strong> Merci. Veuillez remplir ce formulaire avec vos coordonnées. Nous vous contacterons dès que nous aurons des nouvelles de votre valise.<br>
        <strong>Traveler:</strong> Dans combien de temps pensez-vous la retrouver?<br>
        <strong>Airport Staff:</strong> Généralement, nous retrouvons les bagages sous 24 à 48 heures. Nous ferons de notre mieux pour la retrouver rapidement.
    </p>
