<h2>Cultural Note</h2>
<p>In France, it's considered very important to say "Bonjour" when entering a shop or restaurant, and "Au revoir" when leaving. Not doing so is considered impolite. Also, the French appreciate when visitors attempt to speak their language, even if just using basic phrases.</p>
