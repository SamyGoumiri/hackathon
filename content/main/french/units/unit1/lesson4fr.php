<h2>Forming Questions</h2>
<p>There are three main ways to form questions in French:</p>

<h3>1. Intonation</h3>
<p>Simply raise the pitch of your voice at the end of a statement:</p>
<ul>
    <li><span class="french-word">Tu parles français.</span> (You speak French.) - Statement</li>
    <li><span class="french-word">Tu parles français?</span> (Do you speak French?) - Question</li>
</ul>

<h3>2. Est-ce que</h3>
<p>Add "Est-ce que" at the beginning of a statement:</p>
<ul>
    <li><span class="french-word">Est-ce que tu parles français?</span> (Do you speak French?)</li>
    <li><span class="french-word">Est-ce que vous avez un stylo?</span> (Do you have a pen?)</li>
</ul>

<h3>3. Inversion</h3>
<p>Invert the subject and verb, connecting them with a hyphen:</p>
<ul>
    <li><span class="french-word">Parles-tu français?</span> (Do you speak French?)</li>
    <li><span class="french-word">Avez-vous un stylo?</span> (Do you have a pen?)</li>
</ul>

