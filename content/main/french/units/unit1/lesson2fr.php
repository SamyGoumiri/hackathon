        <strong>J sound:</strong> je (I), jardin (garden), bonjour (hello)<br>
        <strong>Ç sound:</strong> français (French), garçon (boy), leçon (lesson)
    </p>
</div>

<h2>Silent Letters</h2>
<p>Many French words have silent letters, especially at the end:</p>
<ul>
    <li>Final consonants are often silent (except c, r, f, l)</li>
    <li>The letter "h" is always silent</li>
    <li>Final "-e" is usually silent or barely pronounced</li>
</ul>
