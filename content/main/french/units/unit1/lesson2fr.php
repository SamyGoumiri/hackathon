<h2>Difficult Consonants</h2>
<p>Some French consonants can be challenging for English speakers:</p>

<ul>
    <li><span class="french-word">R</span> - The French "R" is pronounced at the back of the throat</li>
    <li><span class="french-word">J</span> - Pronounced like the "s" in "measure"</li>
    <li><span class="french-word">Ç</span> - Always pronounced as "s"</li>
</ul>

<div class="example">
    <div class="example-title">Practice Words</div>
