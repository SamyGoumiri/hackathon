<h2>Sightseeing Vocabulary</h2>
<ul>
    <li><span class="german-word">besichtigen</span> (beh-zikh-ti-gen) - to go sightseeing</li>
    <li><span class="german-word">besuchen</span> (beh-zoo-khen) - to visit</li>
    <li><span class="german-word">der Reiseführer/der Stadtführer</span> (dair ry-zeh-fue-rer/dair shtaht-fue-rer) - guide (person or book)</li>
    <li><span class="german-word">die Führung</span> (dee fue-roong) - guided tour</li>
    <li><span class="german-word">der Stadtplan</span> (dair shtaht-plahn) - map</li>
    <li><span class="german-word">die Öffnungszeiten</span> (dee erf-noonks-tsy-ten) - opening hours</li>
    <li><span class="german-word">die Eintrittskarte</span> (dee ayn-trits-kar-teh) - (admission) ticket</li>
    <li><span class="german-word">die Aussicht</span> (dee ows-zikht) - view</li>
    <li><span class="german-word">Fotos machen</span> (fo-tos makh-en) - to take pictures</li>
</ul>

<h2>Useful Phrases for Sightseeing</h2>
<ul>
    <li><span class="german-word">Wann öffnet/schließt es?</span> (vahn erf-net/shleest es) - What time does it open/close?</li>
    <li><span class="german-word">Was kostet der Eintritt?</span> (vas kos-tet dair ayn-trit) - How much is the admission?</li>
    <li><span class="german-word">Gibt es Ermäßigungen für Studenten?</span> (gibt es er-meh-si-goon-gen fuer shtoo-den-ten) - Is there a discount for students?</li>
    <li><span class="german-word">Gibt es eine Führung auf Englisch?</span> (gibt es ay-neh fue-roong owf eng-lish) - Is there a guided tour in English?</li>
    <li><span class="german-word">Darf ich hier fotografieren?</span> (darf ikh heer fo-to-gra-fee-ren) - Can I take pictures here?</li>
    <li><span class="german-word">Wo sind die Toiletten?</span> (vo zint dee twa-let-ten) - Where are the restrooms?</li>
</ul>

