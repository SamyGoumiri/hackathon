<h2>Useful Phrases for Traveling</h2>
<ul>
    <li><span class="german-word">Ich möchte eine Fahrkarte nach...</span> (ikh mekh-teh eye-neh faar-kar-teh nahkh) - I would like a ticket to...</li>
    <li><span class="german-word">Wann fährt der Zug/Bus ab?</span> (van fairt dair tsoog/boos ap) - What time does the train/bus leave?</li>
    <li><span class="german-word">Wo ist die Station/Haltestelle für...?</span> (voh ist dee shta-tsee-ohn/hal-teh-shtel-leh fuer) - Where is the station/stop for...?</li>
    <li><span class="german-word">Ich möchte ein Auto mieten.</span> (ikh mekh-teh ayn ow-toh mee-ten) - I would like to rent a car.</li>
</ul>

<div class="example">
    <div class="example-title">Example Conversation</div>
    <p>
        <strong>Passenger:</strong> Guten Tag, ich hätte gerne eine einfache Fahrkarte nach München, bitte.<br>
        <strong>Ticket Agent:</strong> Guten Tag. Für heute?<br>
        <strong>Passenger:</strong> Ja, für den Zug um 14:30 Uhr.<br>
        <strong>Ticket Agent:</strong> Sehr gut. Das macht 45 Euro.<br>
        <strong>Passenger:</strong> Hier bitte. Fährt der Zug von Gleis 3 ab?<br>
        <strong>Ticket Agent:</strong> Nein, er fährt von Gleis 5 ab. Hier ist Ihre Fahrkarte. Gute Reise!<br>
        <strong>Passenger:</strong> Vielen Dank!
    </p>
</div>

<h2>Common Transportation Issues</h2>
<ul>
    <li><span class="german-word">Der Zug/Bus hat Verspätung.</span> - The train/bus is late.</li>
    <li><span class="german-word">Der Flug ist gestrichen.</span> - The flight is canceled.</li>
    <li><span class="german-word">Ich habe meinen Zug/Bus verpasst.</span> - I missed my train/bus.</li>
    <li><span class="german-word">Wo kann ich eine Fahrkarte kaufen?</span> - Where can I buy a ticket?</li>
    <li><span class="german-word">Kann ich online buchen?</span> - Can I book online?</li>
</ul>

<div class="practice-tip">
    <h3>Practice Tip</h3>
    <p>When using public transportation in Germany, it's common to validate your ticket in a machine before boarding. Look for signs saying "Entwerten" (validate) and machines called "Entwerter".</p>
</div>

