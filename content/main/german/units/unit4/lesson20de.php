<h2>Useful Phrases for Travel Problems</h2>

<h3>Transportation Issues</h3>
<ul>
    <li><span class="german-word">Mein Zug/Flug hat Verspätung/wurde storniert.</span> (myne tsoog/floog hat fair-shpay-toong/voor-deh shtor-neert) - My train/flight has been delayed/cancelled.</li>
    <li><span class="german-word">Ich habe meinen Zug/Flug verpasst.</span> (ikh hah-beh my-nen tsoog/floog fair-passt) - I missed my train/flight.</li>
    <li><span class="german-word">Wann ist die nächste Abfahrt?</span> (vahn ist dee nekh-steh ab-fahrt) - When is the next departure?</li>
    <li><span class="german-word">Kann ich eine Rückerstattung bekommen?</span> (kahn ikh ay-neh ruek-er-shtah-toong beh-kom-men) - Can I get a refund?</li>
</ul>

<h3>Lost Items and Luggage</h3>
<ul>
    <li><span class="german-word">Ich habe mein Gepäck verloren.</span> (ikh hah-beh myn geh-peck fair-lor-en) - I've lost my luggage.</li>
    <li><span class="german-word">Ich habe meine Brieftasche/meinen Reisepass verloren.</span> (ikh hah-beh my-neh breef-tah-sheh/my-nen ry-zeh-pass fair-lor-en) - I've lost my wallet/passport.</li>
    <li><span class="german-word">Wo ist das Fundbüro?</span> (vo ist dahs foond-bue-ro) - Where is the lost and found office?</li>
    <li><span class="german-word">Ich muss einen Diebstahl melden.</span> (ikh moos ay-nen deep-shtahl mel-den) - I need to file a theft report.</li>
</ul>

<h3>Health Issues</h3>
<ul>
    <li><span class="german-word">Ich fühle mich nicht wohl.</span> (ikh fue-leh mikh nikht vohl) - I don't feel well.</li>
    <li><span class="german-word">Ich brauche einen Arzt.</span> (ikh brow-kheh ay-nen artst) - I need a doctor.</li>
    <li><span class="german-word">Wo ist das nächste Krankenhaus?</span> (vo ist dahs nekh-steh krahn-ken-hows) - Where is the nearest hospital?</li>
    <li><span class="german-word">Ich habe eine Reiseversicherung.</span> (ikh hah-beh ay-neh ry-zeh-fair-zikh-er-oong) - I have travel insurance.</li>
</ul>

<h3>General Emergency Phrases</h3>
<ul>
    <li><span class="german-word">Hilfe!</span> (hil-feh) - Help!</li>
    <li><span class="german-word">Es ist ein Notfall!</span> (es ist ayn not-fahl) - It's an emergency!</li>
    <li><span class="german-word">Rufen Sie einen Krankenwagen/die Polizei!</span> (roo-fen zee ay-nen krahn-ken-vah-gen/dee po-lits-eye) - Call an ambulance/the police!</li>
    <li><span class="german-word">Ich brauche Hilfe.</span> (ikh brow-kheh hil-feh) - I need help.</li>
</ul>

<div class="example">
    <div class="example-title">Example Conversation - Lost Luggage</div>
    <p>
        <strong>Traveler:</strong> Entschuldigung, ich habe ein Problem. Ich kann meinen Koffer auf dem Gepäckband nicht finden.<br>
        <strong>Airport Staff:</strong> Es tut mir leid, das zu hören. Können Sie mir Ihren Koffer beschreiben, bitte?<br>
        <strong>Traveler:</strong> Es ist ein großer schwarzer Koffer mit einem roten Anhänger. Mein Name steht darauf.<br>
        <strong>Airport Staff:</strong> In Ordnung. Sie müssen ein Formular für verlorenes Gepäck ausfüllen. Haben Sie Ihr Flugticket und Ihren Gepäckschein?<br>
        <strong>Traveler:</strong> Ja, hier ist mein Ticket und der Schein.<br>
        <strong>Airport Staff:</strong> Danke. Bitte füllen Sie dieses Formular mit Ihren Kontaktdaten aus. Wir werden Sie kontaktieren, sobald wir Neuigkeiten über Ihren Koffer haben.<br>
        <strong>Traveler:</strong> Wie lange dauert es normalerweise, bis man ihn findet?<br>
        <strong>Airport Staff:</strong> Normalerweise finden wir Gepäckstücke innerhalb von 24 bis 48 Stunden. Wir werden unser Bestes tun, um ihn schnell zu finden.
    </p>
</div>

