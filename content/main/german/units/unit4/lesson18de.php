<h2>Booking a Room</h2>
<ul>
    <li><span class="german-word">Ich möchte ein Zimmer reservieren.</span> (ikh merkh-teh ayn tsim-mer reh-zer-vee-ren) - I would like to book a room.</li>
    <li><span class="german-word">Für wie viele Nächte?</span> (fuer vee fee-leh neckh-teh) - For how many nights?</li>
    <li><span class="german-word">Vom [date] bis zum [date].</span> (fom [date] bis tsoom [date]) - From [date] to [date].</li>
    <li><span class="german-word">Haben Sie ein freies Zimmer?</span> (hah-ben zee ayn fry-es tsim-mer) - Do you have a room available?</li>
    <li><span class="german-word">Was kostet das Zimmer pro Nacht?</span> (vas kos-tet dahs tsim-mer pro nakht) - What's the price per night?</li>
    <li><span class="german-word">Ist das Frühstück inklusive?</span> (ist dahs frue-shtuck in-klu-zee-veh) - Is breakfast included?</li>
</ul>

<h2>At Check-in/Check-out</h2>
<ul>
    <li><span class="german-word">Ich habe eine Reservierung auf den Namen...</span> (ikh hah-beh ay-neh reh-zer-vee-roong owf dayn nah-men) - I have a reservation under the name...</li>
    <li><span class="german-word">Um wie viel Uhr ist der Check-out?</span> (um vee feel oor ist dair check-out) - What time is check-out?</li>
    <li><span class="german-word">Ich möchte meinen Aufenthalt verlängern.</span> (ikh merkh-teh my-nen owf-ent-halt fair-leng-ern) - I would like to extend my stay.</li>
    <li><span class="german-word">Ich möchte die Rechnung, bitte.</span> (ikh merkh-teh dee rekh-noong, bit-teh) - I would like the bill, please.</li>
    <li><span class="german-word">Gibt es einen Safe im Zimmer?</span> (gipt es ay-nen sayf im tsim-mer) - Is there a safe in the room?</li>
    <li><span class="german-word">Wie kann ich auf das WLAN zugreifen?</span> (vee kan ikh owf dahs vay-lahn tsoo-gry-fen) - How can I access the Wi-Fi?</li>
</ul>

<div class="example">
    <div class="example-title">Example Conversation - Making a Reservation</div>
    <p>
        <strong>Guest:</strong> Guten Tag, ich möchte ein Zimmer für zwei Personen reservieren, bitte.<br>
        <strong>Receptionist:</strong> Guten Tag. Für welchen Zeitraum?<br>
        <strong>Guest:</strong> Vom 15. bis zum 18. Juni.<br>
        <strong>Receptionist:</strong> Sehr gut. Wir haben ein Doppelzimmer für diesen Zeitraum frei. Es kostet 95 Euro pro Nacht.<br>
        <strong>Guest:</strong> Ist das Frühstück inklusive?<br>
        <strong>Receptionist:</strong> Nein, das Frühstück kostet 12 Euro pro Person.<br>
        <strong>Guest:</strong> In Ordnung, ich nehme das Zimmer. Gibt es WLAN?<br>
        <strong>Receptionist:</strong> Ja, das WLAN ist im ganzen Hotel kostenlos. Darf ich Ihren Namen haben, bitte?<br>
        <strong>Guest:</strong> Mein Name ist Peter Schmidt.
    </p>
</div>

