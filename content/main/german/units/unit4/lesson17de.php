<h2>Asking for Directions</h2>
<ul>
    <li><span class="german-word">Entschuldigung, wo ist...?</span> (ent-shool-di-goong, voh ist) - Excuse me, where is...?</li>
    <li><span class="german-word">Wie komme ich zu...?</span> (vee kom-meh ikh tsoo) - How do I get to...?</li>
    <li><span class="german-word">Könnten Sie mir den Weg zu... zeigen?</span> (kurn-ten zee meer den vehg tsoo... tsy-gen) - Could you show me the way to...?</li>
    <li><span class="german-word">Ich suche...</span> (ikh zoo-kheh) - I'm looking for...</li>
    <li><span class="german-word">Ist es weit?</span> (ist es vite) - Is it far?</li>
    <li><span class="german-word">Wie lange braucht man zu Fuß dorthin?</span> (vee lang-eh browkht mahn tsoo foos dort-hin) - How long does it take to get there on foot?</li>
</ul>

<h2>Giving Directions</h2>
<ul>
    <li><span class="german-word">Biegen Sie rechts/links ab.</span> (bee-gen zee rekhts/links ahb) - Turn right/left.</li>
    <li><span class="german-word">Gehen Sie geradeaus.</span> (gay-en zee geh-rah-deh-ows) - Go straight ahead.</li>
    <li><span class="german-word">Gehen Sie weiter bis...</span> (gay-en zee vy-ter bis) - Continue until...</li>
    <li><span class="german-word">Nehmen Sie die erste/zweite Straße rechts/links.</span> (nay-men zee dee air-steh/tsvy-teh shtrah-seh rekhts/links) - Take the first/second street on the right/left.</li>
    <li><span class="german-word">Es ist ungefähr 10 Minuten zu Fuß.</span> (es ist oon-geh-fair tsayn mi-noo-ten tsoo foos) - It's about 10 minutes on foot.</li>
</ul>

<div class="example">
    <div class="example-title">Example Conversation</div>
    <p>
        <strong>Tourist:</strong> Entschuldigung, wo ist das Brandenburger Tor, bitte?<br>
        <strong>Local:</strong> Das Brandenburger Tor? Also, gehen Sie diese Straße geradeaus für etwa 5 Minuten. Dann biegen Sie links an der Kreuzung ab. Gehen Sie weiter geradeaus und Sie werden das Brandenburger Tor auf der rechten Seite sehen. Es ist ein großes Gebäude mit Säulen.<br>
        <strong>Tourist:</strong> Ist es weit von hier?<br>
        <strong>Local:</strong> Nein, ungefähr 15 Minuten zu Fuß.<br>
        <strong>Tourist:</strong> Vielen Dank für Ihre Hilfe!<br>
        <strong>Local:</strong> Gern geschehen. Schönen Tag noch!
    </p>
</div>

<div class="practice-tip">
    <h3>Practice Tip</h3>
    <p>German people appreciate when you begin your questions with "Entschuldigung" or "Guten Tag" before asking for directions. It's considered more polite than directly asking a question.</p>
