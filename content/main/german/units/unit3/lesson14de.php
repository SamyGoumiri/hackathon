<h2>Talking About Prices</h2>
<ul>
    <li><span class="german-word">Was kostet das?</span> (vas kos-tet das) - How much is it?</li>
    <li><span class="german-word">Wie viel kostet das?</span> (vee feel kos-tet das) - How much does it cost?</li>
    <li><span class="german-word">Das kostet drei Euro fünfzig.</span> (das kos-tet dry oy-ro fuenf-tsikh) - It's €3.50.</li>
    <li><span class="german-word">Das ist teuer.</span> (das ist toy-er) - It's expensive.</li>
    <li><span class="german-word">Das ist günstig.</span> (das ist guens-tikh) - It's inexpensive.</li>
    <li><span class="german-word">Das ist im Angebot.</span> (das ist im an-geh-bot) - It's on sale.</li>
    <li><span class="german-word">Kann ich mit Karte bezahlen?</span> (kan ikh mit kar-teh beh-tsaa-len) - Can I pay by card?</li>
    <li><span class="german-word">Ich habe nicht genug Geld.</span> (ikh hah-beh nikht geh-nook gelt) - I don't have enough money.</li>
</ul>

<div class="example">
    <div class="example-title">Example Conversation About Money</div>
    <p>
        <strong>Customer:</strong> Guten Tag, was kostet dieser Pullover, bitte?<br>
        <strong>Salesperson:</strong> Dieser Pullover kostet neunundvierzig Euro neunzig.<br>
        <strong>Customer:</strong> Das ist ein bisschen teuer. Ist er im Angebot?<br>
        <strong>Salesperson:</strong> Ja, tatsächlich ist das schon der reduzierte Preis. Er hat vorher siebzig Euro gekostet.<br>
        <strong>Customer:</strong> In Ordnung, ich nehme ihn. Kann ich mit Karte bezahlen?<br>
        <strong>Salesperson:</strong> Natürlich, folgen Sie mir bitte zur Kasse.<br>
        <strong>Cashier:</strong> Das macht dann neunundvierzig Euro neunzig.<br>
        <strong>Customer:</strong> Hier ist meine Karte.<br>
        <strong>Cashier:</strong> Danke. Geben Sie bitte Ihre PIN ein.<br>
        <strong>Customer:</strong> So.<br>
        <strong>Cashier:</strong> Vielen Dank für Ihren Einkauf. Auf Wiedersehen!<br>
        <strong>Customer:</strong> Vielen Dank. Auf Wiedersehen!
    </p>
</div>

<p>In Germany and other European countries, prices are written with a comma instead of a decimal point. For example, €3.50 would be written as 3,50 €. Also, the euro symbol (€) often comes after the number, not before as with the dollar sign.</p>
