    <div class="example-title">Example Conversation at a Restaurant</div>
    <p>
        <strong>Server:</strong> Guten Tag, willkommen im Restaurant Berliner Ecke. Ein Tisch für wie viele Personen?<br>
        <strong>Customer:</strong> Guten Tag, ein Tisch für zwei, bitte.<br>
        <strong>Server:</strong> Natürlich. Hier entlang, bitte. Hier ist die Speisekarte.<br>
        <strong>Customer:</strong> Danke. Was empfehlen Sie heute?<br>
        <strong>Server:</strong> Ich empfehle den Schweinebraten, das ist unsere Spezialität.<br>
        <strong>Customer:</strong> Perfekt! Ich nehme das und eine Karaffe Wasser, bitte.<br>
        <strong>Server:</strong> Sehr gute Wahl. Ich bringe es Ihnen sofort.
    </p>
