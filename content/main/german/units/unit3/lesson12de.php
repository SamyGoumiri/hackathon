<h2>Useful Phrases for Ordering</h2>
<ul>
    <li><span class="german-word">Ich möchte einen Tisch für ... reservieren.</span> (ish mersh-tuh ay-nen tish für ... ray-zair-vee-ren) - I would like to book a table for...</li>
    <li><span class="german-word">Einen Tisch für zwei, bitte.</span> (ay-nen tish für tsvai, bi-tuh) - A table for two, please.</li>
    <li><span class="german-word">Kann ich die Speisekarte sehen, bitte?</span> (kan ish dee shpy-zuh-kar-tuh zay-en, bi-tuh) - May I see the menu, please?</li>
    <li><span class="german-word">Ich hätte gerne...</span> (ish het-tuh gair-nuh) - I would like...</li>
    <li><span class="german-word">Was empfehlen Sie?</span> (vas em-pfay-len zee) - What do you recommend?</li>
    <li><span class="german-word">Die Rechnung, bitte.</span> (dee rech-noong, bi-tuh) - The bill, please.</li>
</ul>

<h2>Food Preferences and Dietary Restrictions</h2>
<ul>
    <li><span class="german-word">Ich bin Vegetarier/Vegetarierin.</span> (ish bin vay-guh-tah-ree-er/vay-guh-tah-ree-er-in) - I am vegetarian.</li>
    <li><span class="german-word">Ich bin allergisch gegen...</span> (ish bin al-lair-gish gay-gen) - I am allergic to...</li>
    <li><span class="german-word">Glutenfrei, bitte.</span> (gloo-ten-fry, bi-tuh) - Gluten-free, please.</li>
    <li><span class="german-word">Nicht zu scharf.</span> (nisht tsoo sharf) - Not too spicy.</li>
</ul>

