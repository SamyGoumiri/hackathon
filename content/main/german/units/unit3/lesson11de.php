<h2>Useful Phrases</h2>
<ul>
    <li><span class="german-word">Wo finde ich...?</span> (vo fin-duh ish) - Where is...?</li>
    <li><span class="german-word">Ich suche...</span> (ish zoo-khuh) - I'm looking for...</li>
    <li><span class="german-word">Was kostet...?</span> (vas kos-tet) - How much is...?</li>
    <li><span class="german-word">Das ist alles, danke.</span> (das ist al-les, dank-uh) - That's all, thank you.</li>
</ul>

