<h2>Useful Shopping Phrases</h2>
<ul>
    <li><span class="german-word">Ich suche nach...</span> (ish zoo-khuh nakh) - I'm looking for...</li>
    <li><span class="german-word">Haben Sie das/die... in Größe...</span> (hah-ben zee das/dee... in grur-suh...) - Do you have this... in size...</li>
    <li><span class="german-word">Kann ich das anprobieren?</span> (kan ish das an-pro-bee-ren) - Can I try it on?</li>
    <li><span class="german-word">Die Umkleidekabine?</span> (dee um-kly-duh-ka-bee-nuh) - The fitting room?</li>
    <li><span class="german-word">Steht mir das gut?</span> (shteyt meer das goot) - Does it look good on me?</li>
    <li><span class="german-word">Das ist zu groß/klein.</span> (das ist tsoo grohs/klayn) - It's too big/small.</li>
    <li><span class="german-word">Ich nehme es/sie.</span> (ish nay-muh es/zee) - I'll take it.</li>
</ul>

<div class="example">
    <div class="example-title">Example Conversation in a Clothing Store</div>
    <p>
        <strong>Sales Assistant:</strong> Guten Tag, kann ich Ihnen helfen?<br>
        <strong>Customer:</strong> Guten Tag, ja, ich suche nach einem weißen Hemd.<br>
        <strong>Sales Assistant:</strong> Natürlich. Welche Größe haben Sie?<br>
        <strong>Customer:</strong> Normalerweise trage ich Größe M.<br>
        <strong>Sales Assistant:</strong> Hier ist ein weißes Hemd in Größe M. Möchten Sie es anprobieren?<br>
        <strong>Customer:</strong> Ja, bitte. Wo ist die Umkleidekabine?<br>
        <strong>Sales Assistant:</strong> Dort drüben, rechts.<br>
        <em>[After trying on]</em><br>
        <strong>Customer:</strong> Ich nehme es. Es passt mir sehr gut.<br>
        <strong>Sales Assistant:</strong> Perfekt! Sie können an der Kasse bezahlen.
    </p>
</div>

<p>In Germany, clothing sizes may differ from what you're used to. German sizes for women's clothing are typically 2 sizes higher than US sizes (e.g., US 6 = German 38). For men, European sizing is used with chest measurements in centimeters. It's always a good idea to try clothes on before buying!</p>
