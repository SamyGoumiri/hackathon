    <div class="example-title">Complete Shopping Scenario</div>
    <p>
        <strong>Customer:</strong> <em>[Entering the shop]</em> Guten Tag!<br>
        <strong>Salesperson:</strong> Guten Tag. Kann ich Ihnen helfen?<br>
        <strong>Customer:</strong> Ja, ich suche ein Geschenk für meine Schwester.<br>
        <strong>Salesperson:</strong> Was mag sie denn?<br>
        <strong>Customer:</strong> Sie liest gerne und mag besonders Krimis.<br>
        <strong>Salesperson:</strong> Wir haben eine Krimi-Abteilung hier drüben. Hier sind unsere Neuerscheinungen.<br>
        <strong>Customer:</strong> Dieser hier sieht interessant aus. Was kostet er?<br>
        <strong>Salesperson:</strong> Er kostet zweiundzwanzig Euro fünfzig.<br>
        <strong>Customer:</strong> Perfekt, den nehme ich.<br>
        <strong>Salesperson:</strong> Sehr gute Wahl. Folgen Sie mir bitte zur Kasse.<br>
        <strong>Cashier:</strong> Das macht zweiundzwanzig Euro fünfzig. Wie möchten Sie bezahlen?<br>
        <strong>Customer:</strong> Mit Karte, bitte.<br>
        <strong>Cashier:</strong> Natürlich. Stecken Sie Ihre Karte ein und geben Sie Ihre PIN ein.<br>
        <strong>Customer:</strong> <em>[Completes payment]</em><br>
        <strong>Cashier:</strong> Hier ist Ihr Buch und Ihre Quittung. Möchten Sie eine Tüte?<br>
        <strong>Customer:</strong> Nein danke, ich habe meine eigene Tasche dabei.<br>
        <strong>Cashier:</strong> Sehr gut. Danke für Ihren Einkauf und einen schönen Tag noch!<br>
        <strong>Customer:</strong> Vielen Dank. Auf Wiedersehen!<br>
        <strong>Cashier:</strong> Auf Wiedersehen!
    </p>
