<h2>Useful Purchase Phrases</h2>
<ul>
    <li><span class="german-word">Ich möchte das kaufen.</span> (ikh mekh-teh das kow-fen) - I would like to buy this.</li>
    <li><span class="german-word">Kann ich bar/mit Karte bezahlen?</span> (kan ikh baar/mit kar-teh beh-tsaa-len) - Can I pay in cash/by card?</li>
    <li><span class="german-word">Haben Sie eine Tüte, bitte?</span> (haa-ben zee eye-neh too-teh, bi-teh) - Do you have a bag, please?</li>
    <li><span class="german-word">Kann ich eine Quittung bekommen?</span> (kan ikh eye-neh kvit-toong beh-ko-men) - Can I have a receipt?</li>
    <li><span class="german-word">Kann ich diesen Artikel umtauschen?</span> (kan ikh dee-zen ar-tee-kel oom-tow-shen) - Can I exchange this item?</li>
    <li><span class="german-word">Ich hätte gerne eine Rückerstattung.</span> (ikh het-teh gair-neh eye-neh ruek-er-stat-toong) - I would like a refund.</li>
    <li><span class="german-word">Es ist defekt.</span> (es ist de-fekt) - It's defective.</li>
    <li><span class="german-word">Gibt es eine Garantie?</span> (gibt es eye-neh ga-ran-tee) - Is there a warranty?</li>
</ul>

<h2>Cultural Shopping Tips in Germany</h2>
<ul>
    <li><span class="german-word">Always greet the shopkeeper:</span> It's very important in German culture to say "Guten Tag" when entering a shop and "Auf Wiedersehen" when leaving.</li>
    <li><span class="german-word">Bring your own bag:</span> Many stores charge for plastic bags to reduce waste.</li>
    <li><span class="german-word">Sales periods:</span> Germany has seasonal sales (der Schlussverkauf or der Ausverkauf), usually in January/February and July/August.</li>
    <li><span class="german-word">Return policies:</span> These can be stricter than in some other countries. Always keep your receipt.</li>
    <li><span class="german-word">Sunday closings:</span> Most shops in Germany are closed on Sundays (Sonntag), with few exceptions.</li>
</ul>

