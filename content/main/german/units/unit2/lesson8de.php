<h2>Minutes Before the Hour</h2>
<p>To express minutes before the next hour, you can use "vor":</p>

<table class="vocabulary-table">
    <tr>
        <th>German</th>
        <th>Pronunciation</th>
        <th>English</th>
    </tr>
    <tr>
        <td class="german-word">Es ist fünf vor sieben</td>
        <td class="pronunciation">es ist foonf for zee-ben</td>
        <td>It's 6:55 (5 minutes to 7)</td>
    </tr>
    <tr>
        <td class="german-word">Es ist zehn vor acht</td>
        <td class="pronunciation">es ist tsayn for akht</td>
        <td>It's 7:50 (10 minutes to 8)</td>
    </tr>
    <tr>
        <td class="german-word">Es ist Viertel vor neun</td>
        <td class="pronunciation">es ist feer-tel for noyn</td>
        <td>It's 8:45 (quarter to 9)</td>
    </tr>
    <tr>
        <td class="german-word">Es ist zwanzig vor zehn</td>
        <td class="pronunciation">es ist tsvan-tsikh for tsayn</td>
        <td>It's 9:40 (20 minutes to 10)</td>
    </tr>
</table>

