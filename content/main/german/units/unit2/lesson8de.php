<h2>Telling the Hour</h2>
<p>To tell the hour in German, use "Es ist" followed by the number and "Uhr":</p>

<table class="vocabulary-table">
    <tr>
        <th>German</th>
        <th>Pronunciation</th>
        <th>English</th>
    </tr>
    <tr>
        <td class="german-word">Es ist ein Uhr</td>
        <td class="pronunciation">es ist ayn oor</td>
        <td>It's 1 o'clock</td>
    </tr>
    <tr>
        <td class="german-word">Es ist zwei Uhr</td>
        <td class="pronunciation">es ist tsvay oor</td>
        <td>It's 2 o'clock</td>
    </tr>
    <tr>
        <td class="german-word">Es ist drei Uhr</td>
        <td class="pronunciation">es ist dry oor</td>
        <td>It's 3 o'clock</td>
    </tr>
    <tr>
        <td class="german-word">Es ist zwölf Uhr</td>
        <td class="pronunciation">es ist tsvurlf oor</td>
        <td>It's 12 o'clock</td>
    </tr>
    <tr>
        <td class="german-word">Es ist Mittag</td>
        <td class="pronunciation">es ist mit-tahk</td>
        <td>It's noon (12 PM)</td>
    </tr>
    <tr>
        <td class="german-word">Es ist Mitternacht</td>
        <td class="pronunciation">es ist mit-ter-nakht</td>
        <td>It's midnight (12 AM)</td>
    </tr>
</table>

