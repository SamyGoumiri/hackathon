<h2>Expressing Dates</h2>
<p>In German, dates are typically written and pronounced in the format "day number + month".</p>

<table class="vocabulary-table">
    <tr>
        <th>German</th>
        <th>Pronunciation</th>
        <th>English</th>
    </tr>
    <tr>
        <td class="german-word">Welches Datum haben wir heute?</td>
        <td class="pronunciation">vel-khes dah-toom hah-ben veer hoy-tuh</td>
        <td>What's the date today?</td>
    </tr>
    <tr>
        <td class="german-word">Heute ist der...</td>
        <td class="pronunciation">hoy-tuh ist dair</td>
        <td>Today is the...</td>
