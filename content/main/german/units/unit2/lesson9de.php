<div class="example">
    <div class="example-title">Example Conversation</div>
    <p>
        <strong>Person A:</strong> Welches Datum haben wir heute?<br>
        <strong>Person B:</strong> Heute ist der fünfzehnte September.<br>
        <strong>Person A:</strong> Und welcher Wochentag ist heute?<br>
        <strong>Person B:</strong> Heute ist Donnerstag.<br>
        <strong>Person A:</strong> Danke. Ich habe einen Termin am nächsten Montag, am zwanzigsten September.<br>
        <strong>Person B:</strong> Nein, nächster Montag ist der neunzehnte September.<br>
        <strong>Person A:</strong> Ah, Sie haben Recht. Danke!
    </p>
</div>

