<div class="example">
    <div class="example-title">Example Conversations</div>
    <p>
        <strong>Conversation 1:</strong><br>
        <strong>Person A:</strong> Wie ist das Wetter heute?<br>
        <strong>Person B:</strong> Es ist schön und warm. Es ist sonnig mit ein paar Wolken.<br>
        <strong>Person A:</strong> Wie ist die Temperatur?<br>
        <strong>Person B:</strong> Es ist 25 Grad.<br>
        <strong>Person A:</strong> Das ist perfekt für einen Strandbesuch!
    </p>
    <p>
        <strong>Conversation 2:</strong><br>
        <strong>Person A:</strong> Wie wird das Wetter in Berlin dieses Wochenende?<br>
        <strong>Person B:</strong> Laut Wetterbericht wird es am Samstag regnen und am Sonntag bewölkt sein.<br>
        <strong>Person A:</strong> Wie wird die Temperatur sein?<br>
        <strong>Person B:</strong> Es wird ungefähr 15 Grad sein. Es wird ziemlich kühl.<br>
        <strong>Person A:</strong> Dann nehme ich einen Regenschirm und eine Jacke mit.
    </p>
