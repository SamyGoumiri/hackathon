<p>In this lesson, you'll learn how to conjugate and use common verbs in the present tense in German.</p>

<h2>Regular Verbs (-EN)</h2>
<p>Most German verbs end in -en. Here's how to conjugate them in present tense:</p>

<table class="vocabulary-table">
    <tr>
        <th>Subject</th>
        <th>Ending</th>
        <th>Example: Sprechen (to speak)</th>
    </tr>
    <tr>
        <td class="german-word">ich (I)</td>
        <td class="pronunciation">-e</td>
        <td>ich spreche</td>
    </tr>
    <tr>
        <td class="german-word">du (you, informal)</td>
        <td class="pronunciation">-st</td>
        <td>du sprichst</td>
    </tr>
    <tr>
        <td class="german-word">er/sie/es (he/she/it)</td>
        <td class="pronunciation">-t</td>
        <td>er/sie/es spricht</td>
    </tr>
    <tr>
        <td class="german-word">wir (we)</td>
        <td class="pronunciation">-en</td>
        <td>wir sprechen</td>
    </tr>
    <tr>
        <td class="german-word">ihr (you, plural)</td>
        <td class="pronunciation">-t</td>
        <td>ihr sprecht</td>
    </tr>
    <tr>
        <td class="german-word">sie/Sie (they/you formal)</td>
        <td class="pronunciation">-en</td>
        <td>sie/Sie sprechen</td>
    </tr>
</table>

