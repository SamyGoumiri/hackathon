<div class="example">
    <div class="example-title">Example: Describing Your Daily Routine</div>
    <p>
        <strong>Am Morgen</strong> wache ich um 7 Uhr auf. Ich stehe auf, dann dusche ich und ziehe mich an. Ich frühstücke um 7:30 Uhr.<br><br>
        <strong>Während des Tages</strong> gehe ich um 8 Uhr zur Arbeit. Ich arbeite bis Mittag, dann esse ich zu Mittag. Ich arbeite noch am Nachmittag und gehe um 18 Uhr nach Hause.<br><br>
        <strong>Am Abend</strong> bereite ich das Abendessen zu und esse gegen 19 Uhr. Nach dem Abendessen sehe ich fern oder lese ein Buch. Ich gehe gegen 23 Uhr ins Bett.
    </p>
</div>

