<h2>Difficult Consonants</h2>
<p>Some German consonants can be challenging for English speakers:</p>

<ul>
    <li><span class="german-word">ch</span> - Two sounds: after a, o, u like "kh"; after e, i, ä, ö, ü softer like "hh"</li>
    <li><span class="german-word">r</span> - Rolled at the back of the throat</li>
    <li><span class="german-word">z</span> - Always pronounced as "ts"</li>
</ul>

