<h2>Special Combinations</h2>
<p>Some German letter combinations have specific pronunciations:</p>
<ul>
    <li><span class="german-word">sch</span> - pronounced like "sh" in "ship"</li>
    <li><span class="german-word">st/sp</span> - at beginning of words, pronounced "sht"/"shp"</li>
    <li><span class="german-word">ei</span> - pronounced like "eye"</li>
    <li><span class="german-word">ie</span> - pronounced like "ee"</li>
</ul>
