<h2>Cultural Note</h2>
<p>In Germany, it's considered very important to say "Guten Tag" when entering a shop or restaurant, and "Auf Wiedersehen" when leaving. Not doing so is considered impolite. Also, Germans appreciate when visitors attempt to speak their language, even if just using basic phrases.</p>
