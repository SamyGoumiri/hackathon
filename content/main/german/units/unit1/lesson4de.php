<h2>Forming Questions</h2>
<p>There are two main ways to form questions in German:</p>

<h3>1. Intonation</h3>
<p>Simply raise the pitch of your voice at the end of a statement:</p>
<ul>
    <li><span class="german-word">Du sprichst Deutsch.</span> (You speak German.) - Statement</li>
    <li><span class="german-word">Du sprichst Deutsch?</span> (Do you speak German?) - Question</li>
</ul>

<h3>2. Inversion</h3>
<p>Place the verb at the beginning of the sentence:</p>
<ul>
    <li><span class="german-word">Sprichst du Deutsch?</span> (Do you speak German?)</li>
    <li><span class="german-word">Hast du einen Stift?</span> (Do you have a pen?)</li>
</ul>

