<h2>Introducing Yourself</h2>
<p>To introduce yourself in German, you can use these phrases:</p>

<ul>
    <li><span class="german-word">Ich heiße...</span> (ikh high-seh) - My name is...</li>
    <li><span class="german-word">Ich bin...</span> (ikh bin) - I am...</li>
    <li><span class="german-word">Freut mich</span> (froyt mikh) - Nice to meet you</li>
</ul>

<div class="example">
    <div class="example-title">Example Conversation</div>
    <p>
        <strong>Person A:</strong> Hallo! Ich heiße Marie.<br>
        <strong>Person B:</strong> Hallo Marie! Ich heiße Paul. Freut mich!<br>
        <strong>Person A:</strong> Freut mich auch, Paul!
    </p>
</div>

