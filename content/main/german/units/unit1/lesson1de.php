<h2>Key Points to Remember</h2>
<ul>
    <li>Use "Guten Morgen" in the morning, "Guten Tag" during the day and "Guten Abend" in the evening.</li>
    <li>"Hallo" and "Hi" are informal and can be used with friends and family.</li>
    <li>"Freut mich" works for all genders in German.</li>
</ul>
