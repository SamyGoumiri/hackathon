<h2>Difficult Sounds</h2>
<p>Some Spanish sounds can be challenging for English speakers:</p>

<ul>
    <li><span class="spanish-word">RR</span> - The Spanish rolled "R" is produced by vibrating your tongue against the roof of your mouth</li>
    <li><span class="spanish-word">G + E/I</span> - Pronounced like a stronger H sound</li>
    <li><span class="spanish-word">H</span> - Always silent in Spanish</li>
</ul>

<div class="example">
    <div class="example-title">Practice Words</div>
