<h2>Stress and Accent Marks</h2>
<p>In Spanish, stress rules are regular:</p>
<ul>
    <li>Words ending in a vowel, n, or s are stressed on the next-to-last syllable</li>
    <li>Words ending in other consonants are stressed on the last syllable</li>
    <li>Accent marks (´) indicate exceptions to these rules</li>
</ul>
