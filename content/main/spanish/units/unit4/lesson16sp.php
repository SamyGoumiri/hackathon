<h2>Useful Phrases for Traveling</h2>
<ul>
    <li><span class="spanish-word">Quisiera un billete para...</span> (kee-see-eh-ra oon bee-yeh-teh pa-ra) - I would like a ticket to...</li>
    <li><span class="spanish-word">¿A qué hora sale el tren/autobús?</span> (ah keh oh-ra sa-leh el tren/ow-toh-boos) - What time does the train/bus leave?</li>
    <li><span class="spanish-word">¿Dónde está la estación/parada de...?</span> (don-deh es-tah la es-ta-see-on/pa-ra-da deh) - Where is the station/stop for...?</li>
    <li><span class="spanish-word">Quisiera alquilar un coche.</span> (kee-see-eh-ra al-kee-lar oon ko-cheh) - I would like to rent a car.</li>
</ul>

<div class="example">
    <div class="example-title">Example Conversation</div>
    <p>
        <strong>Passenger:</strong> Buenos días, quisiera un billete sencillo para Madrid, por favor.<br>
        <strong>Ticket Agent:</strong> Buenos días. ¿Para hoy?<br>
        <strong>Passenger:</strong> Sí, para el tren de las 14:30.<br>
        <strong>Ticket Agent:</strong> Muy bien. Son 45 euros.<br>
        <strong>Passenger:</strong> Aquí tiene. ¿El tren sale del andén 3?<br>
        <strong>Ticket Agent:</strong> No, sale del andén 5. Aquí tiene su billete. ¡Buen viaje!<br>
        <strong>Passenger:</strong> ¡Muchas gracias!
    </p>
</div>

<h2>Common Transportation Issues</h2>
<ul>
    <li><span class="spanish-word">El tren/autobús llega con retraso.</span> - The train/bus is late.</li>
    <li><span class="spanish-word">El vuelo está cancelado.</span> - The flight is canceled.</li>
    <li><span class="spanish-word">He perdido mi tren/autobús.</span> - I missed my train/bus.</li>
    <li><span class="spanish-word">¿Dónde puedo comprar un billete?</span> - Where can I buy a ticket?</li>
    <li><span class="spanish-word">¿Puedo reservar en línea?</span> - Can I book online?</li>
</ul>

<div class="practice-tip">
    <h3>Practice Tip</h3>
    <p>When using public transportation in Spain and many Latin American countries, it's common to validate or "cancelar" your ticket in a machine. In some countries like Mexico, you might hear "boleto" instead of "billete" for ticket.</p>
</div>
