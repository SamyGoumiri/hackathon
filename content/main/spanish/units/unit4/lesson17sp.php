<h2>Asking for Directions</h2>
<ul>
    <li><span class="spanish-word">Disculpe, ¿dónde está...?</span> (dis-kool-peh, don-deh es-tah) - Excuse me, where is...?</li>
    <li><span class="spanish-word">¿Cómo llego a...?</span> (ko-mo yeh-go ah) - How do I get to...?</li>
    <li><span class="spanish-word">¿Podría indicarme el camino para...?</span> (poh-dree-ah in-di-kar-meh el ka-mee-no pa-ra) - Could you show me the way to...?</li>
    <li><span class="spanish-word">Estoy buscando...</span> (es-toy boos-kan-do) - I'm looking for...</li>
    <li><span class="spanish-word">¿Está lejos?</span> (es-tah leh-hos) - Is it far?</li>
    <li><span class="spanish-word">¿Cuánto tiempo se tarda a pie?</span> (koo-an-to tee-em-po seh tar-da ah pee-eh) - How long does it take to get there on foot?</li>
</ul>

<h2>Giving Directions</h2>
<ul>
    <li><span class="spanish-word">Gire a la derecha/izquierda.</span> (hee-reh ah la deh-reh-cha/ees-key-er-da) - Turn right/left.</li>
    <li><span class="spanish-word">Siga todo recto.</span> (see-ga toh-doh rek-toh) - Go straight ahead.</li>
    <li><span class="spanish-word">Continúe hasta...</span> (kon-tee-noo-eh has-ta) - Continue until...</li>
    <li><span class="spanish-word">Tome la primera/segunda calle a la derecha/izquierda.</span> (toh-meh la pree-meh-ra/seh-goon-da ka-yeh ah la deh-reh-cha/ees-key-er-da) - Take the first/second street on the right/left.</li>
    <li><span class="spanish-word">Está a unos 10 minutos caminando.</span> (es-tah ah oo-nos dee-es mee-noo-tos ka-mee-nan-do) - It's about 10 minutes on foot.</li>
</ul>

<div class="example">
    <div class="example-title">Example Conversation</div>
    <p>
        <strong>Tourist:</strong> Disculpe, señora. ¿Dónde está el Museo del Prado, por favor?<br>
        <strong>Local:</strong> ¿El Prado? Pues, siga todo recto por esta calle durante unos 5 minutos. Después, gire a la izquierda en el cruce. Continúe recto y verá el museo a su derecha. Es un edificio grande con columnas.<br>
        <strong>Tourist:</strong> ¿Está lejos de aquí?<br>
        <strong>Local:</strong> No, aproximadamente a 15 minutos caminando.<br>
        <strong>Tourist:</strong> ¡Muchas gracias por su ayuda!<br>
        <strong>Local:</strong> De nada. ¡Que tenga un buen día!
    </p>
</div>

<div class="practice-tip">
    <h3>Practice Tip</h3>
    <p>Spanish speakers appreciate when you begin your questions with "Disculpe" or "Buenos días/tardes" before asking for directions. It's considered more polite than directly asking a question.</p>
