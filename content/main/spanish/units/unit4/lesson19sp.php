<h2>Cultural Tips</h2>
<p>When visiting cultural sites in Spain:</p>
<ul>
    <li>Many museums offer free entry during certain times or days (commonly Sunday afternoons)</li>
    <li>Major museums often close one day per week (commonly Monday)</li>
    <li>It's better to book tickets online in advance for popular attractions like La Sagrada Familia or Alhambra</li>
    <li>Photography policies vary by location - always check before taking photos, especially inside churches or museums</li>
</ul>

