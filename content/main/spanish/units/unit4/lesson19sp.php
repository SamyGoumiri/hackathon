        <strong>Tourist:</strong> Gracias. ¿Se pueden sacar fotos dentro?<br>
        <strong>Ticket Agent:</strong> Sí, pero sin flash. Aquí tienen sus entradas y un plano del museo. ¡Que disfruten la visita!<br>
