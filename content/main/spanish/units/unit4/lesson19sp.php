<h2>Sightseeing Vocabulary</h2>
<ul>
    <li><span class="spanish-word">hacer turismo</span> (ah-sehr too-rees-mo) - to go sightseeing</li>
    <li><span class="spanish-word">visitar</span> (bee-see-tar) - to visit</li>
    <li><span class="spanish-word">el guía</span> (el gee-ah) - guide (person or book)</li>
    <li><span class="spanish-word">la visita guiada</span> (lah bee-see-tah gee-ah-dah) - guided tour</li>
    <li><span class="spanish-word">el plano/el mapa</span> (el plah-no/el mah-pah) - map</li>
    <li><span class="spanish-word">el horario de apertura</span> (el o-rah-ree-oh deh ah-pehr-too-rah) - opening hours</li>
    <li><span class="spanish-word">la entrada</span> (lah en-trah-dah) - (admission) ticket</li>
    <li><span class="spanish-word">la vista</span> (lah vees-tah) - view</li>
    <li><span class="spanish-word">sacar fotos</span> (sah-kar fo-tos) - to take pictures</li>
</ul>

<h2>Useful Phrases for Sightseeing</h2>
<ul>
    <li><span class="spanish-word">¿A qué hora abre/cierra?</span> (ah keh o-rah ah-breh/see-eh-rrah) - What time does it open/close?</li>
    <li><span class="spanish-word">¿Cuánto cuesta la entrada?</span> (kwan-toh kwes-tah lah en-trah-dah) - How much is the admission?</li>
    <li><span class="spanish-word">¿Hay descuento para estudiantes?</span> (eye des-kwen-toh pah-rah es-too-dee-an-tes) - Is there a discount for students?</li>
    <li><span class="spanish-word">¿Hay visita guiada en inglés?</span> (eye bee-see-tah gee-ah-dah en een-glays) - Is there a guided tour in English?</li>
    <li><span class="spanish-word">¿Se pueden sacar fotos?</span> (seh pweh-den sah-kar fo-tos) - Can I take pictures?</li>
    <li><span class="spanish-word">¿Dónde están los baños?</span> (don-deh es-tan los bah-nyos) - Where are the restrooms?</li>
</ul>

