<h2>Useful Phrases for Travel Problems</h2>

<h3>Transportation Issues</h3>
<ul>
    <li><span class="spanish-word">Mi tren/vuelo ha sido retrasado/cancelado.</span> (mee tren/vweh-loh ah see-doh reh-trah-sah-doh/kan-seh-lah-doh) - My train/flight has been delayed/cancelled.</li>
    <li><span class="spanish-word">He perdido mi tren/vuelo.</span> (eh pehr-dee-doh mee tren/vweh-loh) - I missed my train/flight.</li>
    <li><span class="spanish-word">¿Cuándo es la próxima salida?</span> (kwan-doh es lah proh-see-mah sah-lee-dah) - When is the next departure?</li>
    <li><span class="spanish-word">¿Puedo obtener un reembolso?</span> (pweh-doh ob-teh-nehr oon reh-em-bol-so) - Can I get a refund?</li>
</ul>

<h3>Lost Items and Luggage</h3>
<ul>
    <li><span class="spanish-word">He perdido mi equipaje.</span> (eh pehr-dee-doh mee eh-kee-pah-heh) - I've lost my luggage.</li>
    <li><span class="spanish-word">He perdido mi cartera/pasaporte.</span> (eh pehr-dee-doh mee kar-teh-rah/pah-sah-por-teh) - I've lost my wallet/passport.</li>
    <li><span class="spanish-word">¿Dónde está la oficina de objetos perdidos?</span> (don-deh es-tah lah oh-fee-see-nah deh ob-heh-tos pehr-dee-dos) - Where is the lost and found office?</li>
    <li><span class="spanish-word">Necesito hacer una denuncia de robo.</span> (neh-seh-see-toh ah-sehr oo-nah deh-noon-see-ah deh ro-bo) - I need to file a theft report.</li>
</ul>

<h3>Health Issues</h3>
<ul>
    <li><span class="spanish-word">No me siento bien.</span> (no meh see-en-toh bee-en) - I don't feel well.</li>
    <li><span class="spanish-word">Necesito un médico.</span> (neh-seh-see-toh oon meh-dee-koh) - I need a doctor.</li>
    <li><span class="spanish-word">¿Dónde está el hospital más cercano?</span> (don-deh es-tah el os-pee-tal mas sehr-kah-no) - Where is the nearest hospital?</li>
    <li><span class="spanish-word">Tengo un seguro de viaje.</span> (ten-go oon seh-goo-roh deh bee-ah-heh) - I have travel insurance.</li>
</ul>

<h3>General Emergency Phrases</h3>
<ul>
    <li><span class="spanish-word">¡Socorro!</span> (so-ko-rro) - Help!</li>
    <li><span class="spanish-word">¡Es una emergencia!</span> (es oo-nah eh-mehr-hen-see-ah) - It's an emergency!</li>
    <li><span class="spanish-word">¡Llame a una ambulancia/la policía!</span> (yah-meh ah oo-nah am-boo-lan-see-ah/lah poh-lee-see-ah) - Call an ambulance/the police!</li>
    <li><span class="spanish-word">Necesito ayuda.</span> (neh-seh-see-toh ah-yoo-dah) - I need help.</li>
</ul>

<div class="example">
    <div class="example-title">Example Conversation - Lost Luggage</div>
    <p>
        <strong>Traveler:</strong> Disculpe, tengo un problema. No encuentro mi maleta en la cinta transportadora.<br>
        <strong>Airport Staff:</strong> Lo siento mucho. ¿Puede describir su maleta, por favor?<br>
        <strong>Traveler:</strong> Es una maleta grande negra con una etiqueta roja. Mi nombre está escrito en ella.<br>
        <strong>Airport Staff:</strong> De acuerdo. Necesita completar un formulario de equipaje perdido. ¿Tiene su billete de avión y la etiqueta del equipaje?<br>
        <strong>Traveler:</strong> Sí, aquí está mi billete y la etiqueta.<br>
        <strong>Airport Staff:</strong> Gracias. Por favor, complete este formulario con sus datos de contacto. Le informaremos en cuanto tengamos noticias de su maleta.<br>
        <strong>Traveler:</strong> ¿Cuánto tiempo cree que tardará en encontrarla?<br>
        <strong>Airport Staff:</strong> Generalmente, encontramos el equipaje dentro de 24 a 48 horas. Haremos todo lo posible para recuperarla rápidamente.
    </p>
</div>

