<h2>Booking a Room</h2>
<ul>
    <li><span class="spanish-word">Me gustaría reservar una habitación.</span> (meh goo-sta-ree-a reh-ser-bar oo-na ah-bee-ta-see-on) - I would like to book a room.</li>
    <li><span class="spanish-word">¿Para cuántas noches?</span> (pa-ra koo-an-tas no-ches) - For how many nights?</li>
    <li><span class="spanish-word">Del [fecha] al [fecha].</span> (del [fecha] al [fecha]) - From [date] to [date].</li>
    <li><span class="spanish-word">¿Tiene una habitación disponible?</span> (tee-eh-neh oo-na ah-bee-ta-see-on dis-po-nee-bleh) - Do you have a room available?</li>
    <li><span class="spanish-word">¿Cuál es el precio por noche?</span> (koo-al es el pre-see-o por no-cheh) - What's the price per night?</li>
    <li><span class="spanish-word">¿Está incluido el desayuno?</span> (es-ta in-kloo-ee-do el deh-sa-yoo-no) - Is breakfast included?</li>
</ul>

<h2>At Check-in/Check-out</h2>
<ul>
    <li><span class="spanish-word">Tengo una reserva a nombre de...</span> (ten-go oo-na reh-ser-ba a nom-breh deh) - I have a reservation under the name...</li>
    <li><span class="spanish-word">¿A qué hora es el check-out?</span> (a keh o-ra es el check-out) - What time is check-out?</li>
    <li><span class="spanish-word">Me gustaría prolongar mi estancia.</span> (meh goo-sta-ree-a pro-lon-gar mee es-tan-see-a) - I would like to extend my stay.</li>
    <li><span class="spanish-word">Quisiera la cuenta, por favor.</span> (kee-see-eh-ra la koo-en-ta por fa-vor) - I would like the bill, please.</li>
    <li><span class="spanish-word">¿Hay una caja fuerte en la habitación?</span> (ai oo-na ka-ha foo-er-teh en la ah-bee-ta-see-on) - Is there a safe in the room?</li>
    <li><span class="spanish-word">¿Cómo puedo acceder al Wi-Fi?</span> (ko-mo poo-eh-do ak-seh-der al wee-fee) - How can I access the Wi-Fi?</li>
</ul>

<div class="example">
    <div class="example-title">Example Conversation - Making a Reservation</div>
    <p>
        <strong>Guest:</strong> Buenos días, me gustaría reservar una habitación para dos personas, por favor.<br>
        <strong>Receptionist:</strong> Buenos días. ¿Para qué fechas?<br>
        <strong>Guest:</strong> Del 15 al 18 de junio.<br>
        <strong>Receptionist:</strong> Muy bien. Tenemos una habitación doble disponible para esas fechas. Son 95 euros por noche.<br>
        <strong>Guest:</strong> ¿Está incluido el desayuno?<br>
        <strong>Receptionist:</strong> No, el desayuno cuesta 12 euros por persona.<br>
        <strong>Guest:</strong> De acuerdo, me quedo con la habitación. ¿Hay Wi-Fi?<br>
        <strong>Receptionist:</strong> Sí, el Wi-Fi es gratuito en todo el hotel. ¿Me puede dar su nombre, por favor?<br>
        <strong>Guest:</strong> Me llamo Pedro González.
    </p>
</div>

