<h2>Expressing Dates</h2>
<p>In Spanish, dates are typically written and pronounced in the format "el + day number + month".</p>

<table class="vocabulary-table">
    <tr>
        <th>Spanish</th>
        <th>Pronunciation</th>
        <th>English</th>
    </tr>
    <tr>
        <td class="spanish-word">¿Cuál es la fecha de hoy?</td>
        <td class="pronunciation">kwahl es lah feh-chah deh oy</td>
        <td>What's the date today?</td>
    </tr>
    <tr>
        <td class="spanish-word">Hoy es el...</td>
        <td class="pronunciation">oy es el</td>
        <td>Today is the...</td>
    </tr>
    <tr>
        <td class="spanish-word">el primero de enero</td>
        <td class="pronunciation">el pree-meh-roh deh eh-neh-roh</td>
        <td>January 1st</td>
    </tr>
    <tr>
        <td class="spanish-word">el dos de febrero</td>
        <td class="pronunciation">el dos deh feh-breh-roh</td>
        <td>February 2nd</td>
    </tr>
    <tr>
        <td class="spanish-word">el quince de marzo</td>
        <td class="pronunciation">el keen-seh deh mar-soh</td>
        <td>March 15th</td>
    </tr>
    <tr>
        <td class="spanish-word">el treinta de abril</td>
        <td class="pronunciation">el treyn-tah deh ah-breel</td>
