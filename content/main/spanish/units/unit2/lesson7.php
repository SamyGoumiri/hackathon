<p>In this lesson, you'll learn how to conjugate and use common verbs in the present tense in French.</p>

<h2>Regular Verbs (-ER)</h2>
<p>Most French verbs end in -er. Here's how to conjugate them in present tense:</p>

<table class="vocabulary-table">
    <tr>
        <th>Subject</th>
        <th>Ending</th>
        <th>Example: Parler (to speak)</th>
    </tr>
    <tr>
        <td class="french-word">je (I)</td>
        <td class="pronunciation">-e</td>
        <td>je parle</td>
    </tr>
    <tr>
        <td class="french-word">tu (you, informal)</td>
        <td class="pronunciation">-es</td>
        <td>tu parles</td>
    </tr>
    <tr>
        <td class="french-word">il/elle/on (he/she/one)</td>
        <td class="pronunciation">-e</td>
        <td>il/elle/on parle</td>
    </tr>
    <tr>
        <td class="french-word">nous (we)</td>
        <td class="pronunciation">-ons</td>
        <td>nous parlons</td>
    </tr>
    <tr>
        <td class="french-word">vous (you, formal/plural)</td>
        <td class="pronunciation">-ez</td>
        <td>vous parlez</td>
    </tr>
    <tr>
        <td class="french-word">ils/elles (they)</td>
        <td class="pronunciation">-ent</td>
        <td>ils/elles parlent</td>
    </tr>
</table>

