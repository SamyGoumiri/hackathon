<div class="example">
    <div class="example-title">Example Sentences</div>
    <p>
        <strong>Regular -ER verb:</strong> Je travaille à Paris. (I work in Paris.)<br>
        <strong>Regular -IR verb:</strong> Nous finissons le projet demain. (We will finish the project tomorrow.)<br>
        <strong>Regular -RE verb:</strong> Ils vendent leur maison. (They are selling their house.)<br>
        <strong>Être:</strong> Je suis médecin. (I am a doctor.)<br>
        <strong>Avoir:</strong> Tu as une belle voiture. (You have a beautiful car.)<br>
        <strong>Faire:</strong> Elle fait ses devoirs. (She is doing her homework.)<br>
        <strong>Aller:</strong> Nous allons au cinéma. (We are going to the cinema.)
    </p>
