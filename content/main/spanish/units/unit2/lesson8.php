<h2>Minutes Before the Hour</h2>
<p>To express minutes before the next hour, you can use "moins":</p>

<table class="vocabulary-table">
    <tr>
        <th>French</th>
        <th>Pronunciation</th>
        <th>English</th>
    </tr>
    <tr>
        <td class="french-word">Il est sept heures moins cinq</td>
        <td class="pronunciation">eel ay set eur mwan sank</td>
        <td>It's 6:55 (5 minutes to 7)</td>
    </tr>
    <tr>
        <td class="french-word">Il est huit heures moins dix</td>
        <td class="pronunciation">eel ay weet eur mwan dees</td>
        <td>It's 7:50 (10 minutes to 8)</td>
    </tr>
    <tr>
        <td class="french-word">Il est neuf heures moins le quart</td>
        <td class="pronunciation">eel ay nuhf eur mwan luh kar</td>
        <td>It's 8:45 (quarter to 9)</td>
    </tr>
    <tr>
        <td class="french-word">Il est dix heures moins vingt</td>
        <td class="pronunciation">eel ay dees eur mwan van</td>
        <td>It's 9:40 (20 minutes to 10)</td>
    </tr>
</table>

