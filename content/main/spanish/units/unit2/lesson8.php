        <td class="pronunciation">eel ay oon eur</td>
        <td>It's 1 o'clock</td>
    </tr>
    <tr>
        <td class="french-word">Il est deux heures</td>
        <td class="pronunciation">eel ay duh zeur</td>
        <td>It's 2 o'clock</td>
    </tr>
    <tr>
        <td class="french-word">Il est trois heures</td>
        <td class="pronunciation">eel ay trwa zeur</td>
        <td>It's 3 o'clock</td>
    </tr>
    <tr>
        <td class="french-word">Il est midi</td>
        <td class="pronunciation">eel ay mee-dee</td>
        <td>It's noon (12 PM)</td>
