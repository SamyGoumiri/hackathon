<h2>Telling the Hour</h2>
<p>To tell the hour in French, use "Il est" followed by the number and "heure(s)":</p>

<table class="vocabulary-table">
    <tr>
        <th>French</th>
        <th>Pronunciation</th>
        <th>English</th>
    </tr>
    <tr>
