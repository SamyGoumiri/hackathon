<h2>Useful Shopping Phrases</h2>
<ul>
    <li><span class="spanish-word">Estoy buscando...</span> (es-toy bus-can-do) - I'm looking for...</li>
    <li><span class="spanish-word">¿Tiene esto en talla...?</span> (tee-eh-neh es-toh en tah-yah) - Do you have this in size...?</li>
    <li><span class="spanish-word">¿Me lo puedo probar?</span> (meh loh pweh-doh pro-bar) - Can I try it on?</li>
    <li><span class="spanish-word">¿Dónde están los probadores?</span> (don-deh es-tan lohs pro-bah-doh-res) - Where are the fitting rooms?</li>
    <li><span class="spanish-word">¿Me queda bien?</span> (meh keh-dah bee-en) - Does it look good on me?</li>
    <li><span class="spanish-word">Es demasiado grande/pequeño.</span> (es deh-mah-see-ah-doh grahn-deh/peh-keh-nyoh) - It's too big/small.</li>
    <li><span class="spanish-word">Me lo/la llevo.</span> (meh loh/lah yeh-boh) - I'll take it.</li>
</ul>

<div class="example">
    <div class="example-title">Example Conversation in a Clothing Store</div>
    <p>
        <strong>Sales Assistant:</strong> Buenos días, ¿puedo ayudarle?<br>
        <strong>Customer:</strong> Buenos días, sí, estoy buscando una camisa blanca.<br>
        <strong>Sales Assistant:</strong> Por supuesto. ¿Qué talla usa?<br>
        <strong>Customer:</strong> Normalmente uso la M.<br>
        <strong>Sales Assistant:</strong> Aquí tiene una camisa blanca en talla M. ¿Quiere probársela?<br>
        <strong>Customer:</strong> Sí, gracias. ¿Dónde están los probadores?<br>
        <strong>Sales Assistant:</strong> Por allí, a la derecha.<br>
        <em>[After trying on]</em><br>
        <strong>Customer:</strong> Me la llevo. Me queda muy bien.<br>
        <strong>Sales Assistant:</strong> ¡Perfecto! Puede pagar en la caja.
    </p>
</div>

<p>In Spain, clothing sizes may differ from what you're used to. European sizes for women's clothing are typically 2-4 sizes higher than US sizes (e.g., US 6 = European 38-40). For men, you may need to convert from inches to centimeters for pants. It's always a good idea to try clothes on before buying!</p>
