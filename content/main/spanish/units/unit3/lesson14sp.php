<h2>Talking About Prices</h2>
<ul>
    <li><span class="spanish-word">¿Cuánto cuesta?</span> (kwahn-to kwehs-tah) - How much is it?</li>
    <li><span class="spanish-word">¿Cuánto vale?</span> (kwahn-to bah-leh) - How much does it cost?</li>
    <li><span class="spanish-word">Son tres euros cincuenta.</span> (son tres eh-oo-ros sin-kwen-tah) - It's €3.50.</li>
    <li><span class="spanish-word">Es caro.</span> (es kah-ro) - It's expensive.</li>
    <li><span class="spanish-word">Es barato.</span> (es bah-rah-to) - It's inexpensive.</li>
    <li><span class="spanish-word">Está en oferta.</span> (es-tah en oh-fer-tah) - It's on sale.</li>
    <li><span class="spanish-word">¿Puedo pagar con tarjeta?</span> (pwe-do pah-gar kon tar-heh-tah) - Can I pay by card?</li>
    <li><span class="spanish-word">No tengo suficiente dinero.</span> (no ten-go soo-fee-see-en-teh dee-neh-ro) - I don't have enough money.</li>
</ul>

<div class="example">
    <div class="example-title">Example Conversation About Money</div>
    <p>
        <strong>Customer:</strong> Buenos días, ¿cuánto cuesta este jersey, por favor?<br>
        <strong>Salesperson:</strong> Este jersey cuesta cuarenta y nueve euros con noventa céntimos.<br>
        <strong>Customer:</strong> Es un poco caro. ¿Está en oferta?<br>
        <strong>Salesperson:</strong> Sí, de hecho, ya tiene el precio rebajado. Antes costaba setenta euros.<br>
        <strong>Customer:</strong> De acuerdo, me lo llevo. ¿Puedo pagar con tarjeta?<br>
        <strong>Salesperson:</strong> Por supuesto, sígame a la caja.<br>
        <strong>Cashier:</strong> Son cuarenta y nueve euros con noventa céntimos.<br>
        <strong>Customer:</strong> Aquí tiene mi tarjeta.<br>
        <strong>Cashier:</strong> Gracias. Introduzca su código, por favor.<br>
        <strong>Customer:</strong> Aquí está.<br>
        <strong>Cashier:</strong> Gracias por su compra. ¡Adiós!<br>
        <strong>Customer:</strong> Muchas gracias. ¡Adiós!
    </p>
</div>

<p>In Spain and other Spanish-speaking countries, prices are written with a comma instead of a decimal point. For example, €3.50 would be written as 3,50 €. Also, the euro symbol (€) often comes after the number, not before as with the dollar sign.</p>
