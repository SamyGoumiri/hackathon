        <strong>Salesperson:</strong> ¿Qué le gusta?<br>
        <strong>Customer:</strong> Le gusta leer y le encantan las novelas policíacas.<br>
        <strong>Salesperson:</strong> Tenemos una sección de novelas policíacas por aquí. Estas son nuestras novedades.<br>
        <strong>Customer:</strong> Esta parece interesante. ¿Cuánto cuesta?<br>
        <strong>Salesperson:</strong> Cuesta veintidós euros con cincuenta.<br>
        <strong>Customer:</strong> Perfecto, me la llevo.<br>
        <strong>Salesperson:</strong> Muy buena elección. Sígame a la caja.<br>
        <strong>Cashier:</strong> Son veintidós euros con cincuenta. ¿Cómo desea pagar?<br>
        <strong>Customer:</strong> Con tarjeta, por favor.<br>
        <strong>Cashier:</strong> Por supuesto. Inserte su tarjeta e introduzca su código.<br>
        <strong>Customer:</strong> <em>[Completes payment]</em><br>
        <strong>Cashier:</strong> Aquí tiene su libro y su recibo. ¿Quiere una bolsa?<br>
        <strong>Customer:</strong> No, gracias, tengo mi propia bolsa.<br>
        <strong>Cashier:</strong> Muy bien. Gracias por su visita y ¡que tenga un buen día!<br>
        <strong>Customer:</strong> Muchas gracias. ¡Adiós!<br>
        <strong>Cashier:</strong> ¡Adiós!
    </p>
