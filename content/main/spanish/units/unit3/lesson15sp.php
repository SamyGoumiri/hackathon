<h2>Useful Purchase Phrases</h2>
<ul>
    <li><span class="spanish-word">Quisiera comprar esto.</span> (kee-see-eh-rah kom-prar es-to) - I would like to buy this.</li>
    <li><span class="spanish-word">¿Puedo pagar en efectivo/con tarjeta?</span> (pwe-do pah-gar en eh-fek-tee-vo/kon tar-heh-tah) - Can I pay in cash/by card?</li>
    <li><span class="spanish-word">¿Tiene una bolsa, por favor?</span> (tee-eh-neh oo-nah bol-sah, por fah-vor) - Do you have a bag, please?</li>
    <li><span class="spanish-word">¿Puedo tener un recibo?</span> (pwe-do teh-nehr oon reh-see-bo) - Can I have a receipt?</li>
    <li><span class="spanish-word">¿Puedo cambiar este artículo?</span> (pwe-do kam-bee-ar es-teh ar-tee-koo-lo) - Can I exchange this item?</li>
    <li><span class="spanish-word">Quisiera un reembolso.</span> (kee-see-eh-rah oon reh-em-bol-so) - I would like a refund.</li>
    <li><span class="spanish-word">Está defectuoso.</span> (es-tah deh-fek-too-o-so) - It's defective.</li>
    <li><span class="spanish-word">¿Hay garantía?</span> (eye gah-ran-tee-ah) - Is there a warranty?</li>
</ul>

<h2>Cultural Shopping Tips in Spain</h2>
<ul>
    <li><span class="spanish-word">Always greet the shopkeeper:</span> It's very important in Spanish culture to say "Buenos días/Buenas tardes" when entering a shop and "Adiós" when leaving.</li>
    <li><span class="spanish-word">Bring your own bag:</span> Many stores charge for plastic bags to reduce waste.</li>
    <li><span class="spanish-word">Sales periods:</span> Spain has regulated sales periods (las rebajas) twice a year, usually in January and July.</li>
    <li><span class="spanish-word">Return policies:</span> These can be stricter than in some other countries. Always keep your receipt.</li>
    <li><span class="spanish-word">Siesta hours:</span> In smaller towns and some cities, shops may close for a few hours in the afternoon for siesta, typically reopening around 4:30 or 5:00 PM.</li>
</ul>

