<p>In Spain, service (tip) is often included in the bill, but leaving 5-10% for good service is common. Spaniards usually eat dinner later than in many other countries, with restaurants often not opening until 8:00 or 8:30 PM and peak dining time around 9:30-10:30 PM.</p>
