<h2>Useful Phrases for Ordering</h2>
<ul>
    <li><span class="spanish-word">Me gustaría reservar una mesa para...</span> (meh goos-tah-ree-ah reh-ser-bar oo-nah meh-sah pah-rah) - I would like to book a table for...</li>
    <li><span class="spanish-word">Una mesa para dos, por favor.</span> (oo-nah meh-sah pah-rah dohs, por fah-vor) - A table for two, please.</li>
    <li><span class="spanish-word">¿Puedo ver la carta, por favor?</span> (pweh-doh vehr lah kar-tah, por fah-vor) - May I see the menu, please?</li>
    <li><span class="spanish-word">Quisiera...</span> (kee-see-eh-rah) - I would like...</li>
    <li><span class="spanish-word">¿Qué recomienda?</span> (keh reh-koh-mee-en-dah) - What do you recommend?</li>
    <li><span class="spanish-word">La cuenta, por favor.</span> (lah kwen-tah, por fah-vor) - The bill, please.</li>
</ul>

<h2>Food Preferences and Dietary Restrictions</h2>
<ul>
    <li><span class="spanish-word">Soy vegetariano(a).</span> (soy veh-heh-tah-ree-ah-no/nah) - I am vegetarian.</li>
    <li><span class="spanish-word">Soy alérgico(a) a...</span> (soy ah-lehr-hee-koh/kah ah) - I am allergic to...</li>
    <li><span class="spanish-word">Sin gluten, por favor.</span> (seen gloo-ten, por fah-vor) - Gluten-free, please.</li>
    <li><span class="spanish-word">No muy picante.</span> (no moo-ee pee-kan-teh) - Not too spicy.</li>
</ul>

<div class="example">
    <div class="example-title">Example Conversation at a Restaurant</div>
    <p>
        <strong>Server:</strong> Buenas tardes, bienvenido a La Taberna Española. ¿Mesa para cuántas personas?<br>
        <strong>Customer:</strong> Buenas tardes, una mesa para dos, por favor.<br>
        <strong>Server:</strong> Por supuesto. Por aquí, por favor. Aquí tiene la carta.<br>
        <strong>Customer:</strong> Gracias. ¿Qué recomienda hoy?<br>
        <strong>Server:</strong> Le recomiendo la paella, es nuestra especialidad.<br>
        <strong>Customer:</strong> ¡Perfecto! Tomaré eso y una jarra de agua, por favor.<br>
        <strong>Server:</strong> Muy buena elección. Se lo traigo enseguida.
    </p>
