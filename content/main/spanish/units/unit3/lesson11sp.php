<h2>Useful Phrases</h2>
<ul>
    <li><span class="spanish-word">¿Dónde está...?</span> (dohn-deh ehs-tah) - Where is...?</li>
    <li><span class="spanish-word">Estoy buscando...</span> (ehs-toy boos-cahn-doh) - I'm looking for...</li>
    <li><span class="spanish-word">¿Cuánto cuesta...?</span> (kwahn-toh kwes-tah) - How much is...?</li>
    <li><span class="spanish-word">Eso es todo, gracias.</span> (eh-soh ehs toh-doh, grah-thee-ahs) - That's all, thank you.</li>
</ul>

