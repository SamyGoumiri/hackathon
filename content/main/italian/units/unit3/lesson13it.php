<h2>Frasi Utili per lo Shopping</h2>
<ul>
    <li><span class="italian-word">Sto cercando...</span> (stoh cher-kan-doh) - I'm looking for...</li>
    <li><span class="italian-word">Avete questo/questa... nella taglia...</span> (ah-veh-teh kwes-to/kwes-tah... nel-la ta-lya) - Do you have this... in size...</li>
    <li><span class="italian-word">Posso provarlo?</span> (pos-so pro-var-lo) - Can I try it on?</li>
    <li><span class="italian-word">Il camerino?</span> (eel ka-meh-ree-no) - The fitting room?</li>
    <li><span class="italian-word">Mi sta bene?</span> (mee stah beh-neh) - Does it look good on me?</li>
    <li><span class="italian-word">È troppo grande/piccolo.</span> (eh trop-po gran-deh/peek-ko-lo) - It's too big/small.</li>
    <li><span class="italian-word">Lo/La prendo.</span> (lo/lah pren-doh) - I'll take it.</li>
</ul>

<div class="example">
    <div class="example-title">Esempio di Conversazione in un Negozio di Abbigliamento</div>
    <p>
        <strong>Commesso:</strong> Buongiorno, posso aiutarla?<br>
        <strong>Cliente:</strong> Buongiorno, sì, sto cercando una camicia bianca.<br>
        <strong>Commesso:</strong> Certamente. Quale taglia porta?<br>
        <strong>Cliente:</strong> Di solito porto una M.<br>
        <strong>Commesso:</strong> Ecco una camicia bianca taglia M. Vuole provarla?<br>
        <strong>Cliente:</strong> Sì, grazie. Dov'è il camerino?<br>
        <strong>Commesso:</strong> Da questa parte, a destra.<br>
        <em>[Dopo la prova]</em><br>
        <strong>Cliente:</strong> La prendo. Mi sta molto bene.<br>
        <strong>Commesso:</strong> Perfetto! Può pagare alla cassa.
    </p>
</div>

<p>In Italia, le taglie dei vestiti potrebbero differire da quelle a cui sei abituato. Le taglie italiane per l'abbigliamento femminile sono in genere numerate da 38 a 52 (38 corrisponde a una taglia XS). Per gli uomini, potrebbe essere necessario convertire da pollici a centimetri per i pantaloni. È sempre una buona idea provare i vestiti prima di acquistarli!</p>
