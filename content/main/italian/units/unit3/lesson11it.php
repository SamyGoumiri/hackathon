<h2>Frasi Utili</h2>
<ul>
    <li><span class="italian-word">Dove si trova...?</span> (doh-veh see troh-vah) - Where is...?</li>
    <li><span class="italian-word">Sto cercando...</span> (stoh cher-kan-doh) - I'm looking for...</li>
    <li><span class="italian-word">Quanto costa...?</span> (kwan-toh kos-tah) - How much is...?</li>
    <li><span class="italian-word">È tutto, grazie.</span> (eh toot-toh, grah-tsee-eh) - That's all, thank you.</li>
</ul>

