<h2>Frasi Utili per Ordinare</h2>
<ul>
    <li><span class="italian-word">Vorrei prenotare un tavolo per...</span> (vor-rey preh-no-ta-reh oon ta-vo-lo per) - I would like to book a table for...</li>
    <li><span class="italian-word">Un tavolo per due, per favore.</span> (oon ta-vo-lo per doo-eh, per fa-vo-reh) - A table for two, please.</li>
    <li><span class="italian-word">Posso vedere il menu, per favore?</span> (pos-so veh-deh-reh eel meh-noo, per fa-vo-reh) - May I see the menu, please?</li>
    <li><span class="italian-word">Vorrei...</span> (vor-rey) - I would like...</li>
    <li><span class="italian-word">Cosa mi consiglia?</span> (ko-sa mee kon-see-lyah) - What do you recommend?</li>
    <li><span class="italian-word">Il conto, per favore.</span> (eel kon-toh, per fa-vo-reh) - The bill, please.</li>
</ul>

<h2>Preferenze Alimentari e Restrizioni Dietetiche</h2>
<ul>
    <li><span class="italian-word">Sono vegetariano/a.</span> (so-no ve-je-ta-rya-no/a) - I am vegetarian.</li>
    <li><span class="italian-word">Sono allergico/a a...</span> (so-no al-ler-jee-ko/ka ah) - I am allergic to...</li>
    <li><span class="italian-word">Senza glutine, per favore.</span> (sen-tsa gloo-tee-neh, per fa-vo-reh) - Gluten-free, please.</li>
    <li><span class="italian-word">Non troppo piccante.</span> (non trop-po pik-kan-teh) - Not too spicy.</li>
</ul>

<div class="example">
    <div class="example-title">Esempio di Conversazione al Ristorante</div>
    <p>
        <strong>Cameriere:</strong> Buongiorno, benvenuti alla Trattoria Romana. Un tavolo per quante persone?<br>
        <strong>Cliente:</strong> Buongiorno, un tavolo per due, per favore.<br>
        <strong>Cameriere:</strong> Certamente. Da questa parte, prego. Ecco il menu.<br>
        <strong>Cliente:</strong> Grazie. Cosa ci consiglia oggi?<br>
        <strong>Cameriere:</strong> Le consiglio la pasta alla carbonara, è la nostra specialità.<br>
        <strong>Cliente:</strong> Perfetto! Prenderò quella e una caraffa d'acqua, per favore.<br>
        <strong>Cameriere:</strong> Ottima scelta. Porto subito.
    </p>
</div>

<p>In Italia, il servizio (mancia) è spesso incluso nel conto come "coperto". La maggior parte degli italiani cena più tardi rispetto a molti altri paesi, con i ristoranti che aprono spesso non prima delle 19:00 o 19:30 e l'orario di punta intorno alle 20:30-21:00.</p>
