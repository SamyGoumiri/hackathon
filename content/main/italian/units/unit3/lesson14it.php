<h2>Parlare di Prezzi</h2>
<ul>
    <li><span class="italian-word">Quanto costa?</span> (kwan-to cos-tah) - How much is it?</li>
    <li><span class="italian-word">Quanto viene?</span> (kwan-to vyeh-neh) - How much does it cost?</li>
    <li><span class="italian-word">Sono tre euro e cinquanta.</span> (so-no treh eh-oo-ro eh chin-kwan-tah) - It's €3.50.</li>
    <li><span class="italian-word">È caro.</span> (eh ca-ro) - It's expensive.</li>
    <li><span class="italian-word">È economico.</span> (eh e-co-no-mee-co) - It's inexpensive.</li>
    <li><span class="italian-word">È in saldo.</span> (eh in sal-do) - It's on sale.</li>
    <li><span class="italian-word">Posso pagare con la carta?</span> (pos-so pa-ga-reh con lah car-tah) - Can I pay by card?</li>
    <li><span class="italian-word">Non ho abbastanza soldi.</span> (non o ab-bas-tan-za sol-dee) - I don't have enough money.</li>
</ul>

<div class="example">
    <div class="example-title">Esempio di Conversazione sul Denaro</div>
    <p>
        <strong>Cliente:</strong> Buongiorno, quanto costa questo maglione, per favore?<br>
        <strong>Commesso:</strong> Questo maglione costa quarantanove euro e novanta.<br>
        <strong>Cliente:</strong> È un po' caro. È in saldo?<br>
        <strong>Commesso:</strong> Sì, in effetti, è già il prezzo scontato. Prima costava settanta euro.<br>
        <strong>Cliente:</strong> Va bene, lo prendo. Posso pagare con la carta?<br>
        <strong>Commesso:</strong> Certamente, mi segua alla cassa.<br>
        <strong>Cassiere:</strong> Sono quarantanove euro e novanta.<br>
        <strong>Cliente:</strong> Ecco la mia carta.<br>
        <strong>Cassiere:</strong> Grazie. Digiti il PIN, per favore.<br>
        <strong>Cliente:</strong> Ecco fatto.<br>
        <strong>Cassiere:</strong> Grazie per il suo acquisto. Arrivederci!<br>
        <strong>Cliente:</strong> Grazie mille. Arrivederci!
    </p>
</div>

<p>In Italia e in altri paesi europei, i prezzi sono scritti con una virgola invece di un punto decimale. Per esempio, €3.50 sarebbe scritto come 3,50 €. Inoltre, il simbolo dell'euro (€) spesso viene dopo il numero, non prima come con il simbolo del dollaro.</p>
