<h2>Frasi Utili per gli Acquisti</h2>
<ul>
    <li><span class="italian-word">Vorrei comprare questo.</span> (vor-rey com-prah-reh kwes-to) - I would like to buy this.</li>
    <li><span class="italian-word">Posso pagare in contanti/con carta?</span> (pos-so pah-gah-reh een con-tan-tee/con car-tah) - Can I pay in cash/by card?</li>
    <li><span class="italian-word">Ha una borsa, per favore?</span> (ah oo-nah bor-sah, per fah-vo-reh) - Do you have a bag, please?</li>
    <li><span class="italian-word">Posso avere lo scontrino?</span> (pos-so ah-veh-reh lo scon-tree-no) - Can I have a receipt?</li>
    <li><span class="italian-word">Posso cambiare questo articolo?</span> (pos-so cam-bee-ah-reh kwes-to ar-tee-co-lo) - Can I exchange this item?</li>
    <li><span class="italian-word">Vorrei un rimborso.</span> (vor-rey oon reem-bor-so) - I would like a refund.</li>
    <li><span class="italian-word">È difettoso.</span> (eh dee-fet-toh-so) - It's defective.</li>
    <li><span class="italian-word">C'è una garanzia?</span> (cheh oo-nah gah-ran-zee-ah) - Is there a warranty?</li>
</ul>

<h2>Consigli Culturali per lo Shopping in Italia</h2>
<ul>
    <li><span class="italian-word">Salutare sempre il negoziante:</span> È molto importante nella cultura italiana dire "Buongiorno" quando si entra in un negozio e "Arrivederci" quando si esce.</li>
    <li><span class="italian-word">Portare la propria borsa:</span> Molti negozi fanno pagare i sacchetti di plastica per ridurre gli sprechi.</li>
    <li><span class="italian-word">Periodi di saldi:</span> L'Italia ha periodi di saldi regolamentati (i saldi) due volte all'anno, solitamente a gennaio e luglio.</li>
    <li><span class="italian-word">Politiche di reso:</span> Queste possono essere più severe rispetto ad altri paesi. Conserva sempre lo scontrino.</li>
    <li><span class="italian-word">Chiusure domenicali:</span> Molti negozi in Italia sono chiusi la domenica, anche se questa situazione sta cambiando nelle città più grandi e nelle zone turistiche.</li>
</ul>

<div class="example">
    <div class="example-title">Scenario Completo di Shopping</div>
    <p>
        <strong>Cliente:</strong> <em>[Entrando nel negozio]</em> Buongiorno!<br>
        <strong>Commesso:</strong> Buongiorno, signora/signore. Posso aiutarla?<br>
        <strong>Cliente:</strong> Sì, sto cercando un regalo per mia sorella.<br>
        <strong>Commesso:</strong> Cosa le piace?<br>
        <strong>Cliente:</strong> Le piace leggere e adora i gialli.<br>
        <strong>Commesso:</strong> Abbiamo una sezione di gialli da questa parte. Ecco le nostre novità.<br>
        <strong>Cliente:</strong> Questo sembra interessante. Quanto costa?<br>
        <strong>Commesso:</strong> Costa ventidue euro e cinquanta.<br>
        <strong>Cliente:</strong> Perfetto, lo prendo.<br>
        <strong>Commesso:</strong> Ottima scelta. Mi segua alla cassa.<br>
        <strong>Cassiere:</strong> Sono ventidue euro e cinquanta. Come desidera pagare?<br>
        <strong>Cliente:</strong> Con carta, per favore.<br>
        <strong>Cassiere:</strong> Certo. Inserisca la carta e digiti il PIN.<br>
        <strong>Cliente:</strong> <em>[Completa il pagamento]</em><br>
        <strong>Cassiere:</strong> Ecco il suo libro e lo scontrino. Desidera una borsa?<br>
        <strong>Cliente:</strong> No grazie, ho la mia borsa.<br>
        <strong>Cassiere:</strong> Molto bene. Grazie per l'acquisto e buona giornata!<br>
        <strong>Cliente:</strong> Grazie mille. Arrivederci!<br>
        <strong>Cassiere:</strong> Arrivederci!
    </p>
</div>

<p>Ricorda che le interazioni di shopping in Italia sono spesso più formali rispetto ad alcuni altri paesi. Usare forme di cortesia come "per favore" e "grazie" è essenziale, così come mantenere un tono rispettoso durante tutte le interazioni.</p>
