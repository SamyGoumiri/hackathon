<h2>Chiedere Indicazioni</h2>
<ul>
    <li><span class="italian-word">Mi scusi, dov'è...?</span> (mee skoo-zee, doh-veh) - Excuse me, where is...?</li>
    <li><span class="italian-word">Come arrivo a...?</span> (ko-meh ar-ree-vo ah) - How do I get to...?</li>
    <li><span class="italian-word">Potrebbe indicarmi la strada per...?</span> (po-treb-beh een-dee-kar-mee lah stra-dah per) - Could you show me the way to...?</li>
    <li><span class="italian-word">Sto cercando...</span> (stoh cher-kan-doh) - I'm looking for...</li>
    <li><span class="italian-word">È lontano?</span> (eh lon-tah-no) - Is it far?</li>
    <li><span class="italian-word">Quanto tempo ci vuole per arrivare a piedi?</span> (kwan-toh tem-po chee voo-oh-leh per ar-ree-vah-reh ah pee-eh-dee) - How long does it take to get there on foot?</li>
</ul>

<h2>Dare Indicazioni</h2>
<ul>
    <li><span class="italian-word">Giri a destra/sinistra.</span> (jee-ree ah des-trah/see-nees-trah) - Turn right/left.</li>
    <li><span class="italian-word">Vada dritto.</span> (vah-dah dreet-toh) - Go straight ahead.</li>
    <li><span class="italian-word">Continui fino a...</span> (kon-tee-noo-ee fee-no ah) - Continue until...</li>
    <li><span class="italian-word">Prenda la prima/seconda via a destra/sinistra.</span> (pren-dah lah pree-mah/seh-kon-dah vee-ah ah des-trah/see-nees-trah) - Take the first/second street on the right/left.</li>
    <li><span class="italian-word">È a circa 10 minuti a piedi.</span> (eh ah cheer-kah dee-eh-chee mee-noo-tee ah pee-eh-dee) - It's about 10 minutes on foot.</li>
</ul>

<div class="example">
    <div class="example-title">Esempio di Conversazione</div>
    <p>
        <strong>Turista:</strong> Mi scusi, signora. Dov'è il museo degli Uffizi, per favore?<br>
        <strong>Locale:</strong> Gli Uffizi? Allora, vada dritto su questa via per circa 5 minuti. Poi, giri a sinistra all'incrocio. Continui dritto e vedrà gli Uffizi alla sua destra. È un grande edificio con una piazza davanti.<br>
        <strong>Turista:</strong> È lontano da qui?<br>
        <strong>Locale:</strong> No, a circa 15 minuti a piedi.<br>
        <strong>Turista:</strong> Grazie mille per il suo aiuto!<br>
        <strong>Locale:</strong> Prego. Buona giornata!
    </p>
</div>

<div class="practice-tip">
    <h3>Suggerimento Pratico</h3>
    <p>Gli italiani apprezzano quando inizi le tue domande con "Mi scusi" o "Buongiorno" prima di chiedere indicazioni. È considerato più educato che fare direttamente una domanda.</p>
</div>
