<h2>Useful Phrases for Travel Problems</h2>

<h3>Transportation Issues</h3>
<ul>
    <li><span class="italian-word">Il mio treno/volo è in ritardo/è stato cancellato.</span> (eel mee-o treh-no/vo-lo eh een ree-tar-do/eh stah-to kan-chel-lah-to) - My train/flight has been delayed/cancelled.</li>
    <li><span class="italian-word">Ho perso il mio treno/volo.</span> (oh per-so eel mee-o treh-no/vo-lo) - I missed my train/flight.</li>
    <li><span class="italian-word">Quando è la prossima partenza?</span> (kwan-do eh lah pros-see-mah par-ten-zah) - When is the next departure?</li>
    <li><span class="italian-word">Posso avere un rimborso?</span> (pos-so ah-veh-reh oon reem-bor-so) - Can I get a refund?</li>
</ul>

<h3>Lost Items and Luggage</h3>
<ul>
    <li><span class="italian-word">Ho perso i miei bagagli.</span> (oh per-so ee mee-eh bah-gah-lyee) - I've lost my luggage.</li>
    <li><span class="italian-word">Ho perso il mio portafoglio/passaporto.</span> (oh per-so eel mee-o por-tah-foh-lyo/pas-sa-por-to) - I've lost my wallet/passport.</li>
    <li><span class="italian-word">Dov'è l'ufficio oggetti smarriti?</span> (do-veh loof-fee-cho oh-jet-tee smar-ree-tee) - Where is the lost and found office?</li>
    <li><span class="italian-word">Devo fare una denuncia di furto.</span> (deh-vo fah-reh oo-nah deh-noon-cha dee foor-to) - I need to file a theft report.</li>
</ul>

<h3>Health Issues</h3>
<ul>
    <li><span class="italian-word">Non mi sento bene.</span> (non mee sen-to beh-neh) - I don't feel well.</li>
    <li><span class="italian-word">Ho bisogno di un medico.</span> (oh bee-zo-nyo dee oon meh-dee-ko) - I need a doctor.</li>
    <li><span class="italian-word">Dov'è l'ospedale più vicino?</span> (do-veh lohs-peh-dah-leh pyoo vee-chee-no) - Where is the nearest hospital?</li>
    <li><span class="italian-word">Ho un'assicurazione di viaggio.</span> (oh oo-nas-see-koo-rah-tsyo-neh dee vyah-jo) - I have travel insurance.</li>
</ul>

<h3>General Emergency Phrases</h3>
<ul>
    <li><span class="italian-word">Aiuto!</span> (ah-yoo-to) - Help!</li>
    <li><span class="italian-word">È un'emergenza!</span> (eh oo-neh-mer-jen-zah) - It's an emergency!</li>
    <li><span class="italian-word">Chiamate un'ambulanza/la polizia!</span> (kyah-mah-teh oo-nam-boo-lan-zah/lah po-lee-tsee-ah) - Call an ambulance/the police!</li>
    <li><span class="italian-word">Ho bisogno di aiuto.</span> (oh bee-zo-nyo dee ah-yoo-to) - I need help.</li>
</ul>

<div class="example">
    <div class="example-title">Example Conversation - Lost Luggage</div>
    <p>
        <strong>Traveler:</strong> Mi scusi, ho un problema. Non trovo la mia valigia sul nastro trasportatore.<br>
        <strong>Airport Staff:</strong> Mi dispiace sentirlo. Può descrivere la sua valigia, per favore?<br>
        <strong>Traveler:</strong> È una valigia grande nera con un'etichetta rossa. Il mio nome è scritto sopra.<br>
        <strong>Airport Staff:</strong> Va bene. Deve compilare un modulo per bagagli smarriti. Ha il suo biglietto aereo e l'etichetta del bagaglio?<br>
        <strong>Traveler:</strong> Sì, ecco il mio biglietto e l'etichetta.<br>
        <strong>Airport Staff:</strong> Grazie. Per favore, compili questo modulo con i suoi dati di contatto. La contatteremo non appena avremo notizie della sua valigia.<br>
        <strong>Traveler:</strong> Quanto tempo ci vorrà per ritrovarla?<br>
        <strong>Airport Staff:</strong> Di solito troviamo i bagagli entro 24-48 ore. Faremo del nostro meglio per ritrovarla il prima possibile.
    </p>
</div>

