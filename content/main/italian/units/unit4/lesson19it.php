<h2>Sightseeing Vocabulary</h2>
<ul>
    <li><span class="italian-word">fare turismo</span> (fah-reh too-reez-moh) - to go sightseeing</li>
    <li><span class="italian-word">visitare</span> (vee-zee-tah-reh) - to visit</li>
    <li><span class="italian-word">la guida</span> (lah gwee-dah) - guide (person or book)</li>
    <li><span class="italian-word">la visita guidata</span> (lah vee-zee-tah gwee-dah-tah) - guided tour</li>
    <li><span class="italian-word">la mappa/la cartina</span> (lah map-pah/lah kar-tee-nah) - map</li>
    <li><span class="italian-word">gli orari di apertura</span> (lyee oh-rah-ree dee ah-per-too-rah) - opening hours</li>
    <li><span class="italian-word">il biglietto (d'ingresso)</span> (eel bee-lyet-toh deen-gres-soh) - (admission) ticket</li>
    <li><span class="italian-word">la vista</span> (lah vee-stah) - view</li>
    <li><span class="italian-word">fare delle foto</span> (fah-reh del-leh foh-toh) - to take pictures</li>
</ul>

<h2>Useful Phrases for Sightseeing</h2>
<ul>
    <li><span class="italian-word">A che ora apre/chiude?</span> (ah keh oh-rah ah-preh/kyoo-deh) - What time does it open/close?</li>
    <li><span class="italian-word">Quanto costa l'ingresso?</span> (kwahn-toh kos-tah leen-gres-soh) - How much is the admission?</li>
    <li><span class="italian-word">C'è uno sconto per gli studenti?</span> (cheh oo-noh skon-toh per lyee stoo-den-tee) - Is there a discount for students?</li>
    <li><span class="italian-word">C'è una visita guidata in inglese?</span> (cheh oo-nah vee-zee-tah gwee-dah-tah een een-gleh-seh) - Is there a guided tour in English?</li>
    <li><span class="italian-word">Posso fare delle foto?</span> (pos-soh fah-reh del-leh foh-toh) - Can I take pictures?</li>
    <li><span class="italian-word">Dove sono i bagni?</span> (doh-veh soh-noh ee bah-nyee) - Where are the restrooms?</li>
</ul>

