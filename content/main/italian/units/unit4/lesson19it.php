<h2>Cultural Tips</h2>
<p>When visiting cultural sites in Italy:</p>
<ul>
    <li>Many state museums offer free entry on the first Sunday of each month (Domenica al Museo)</li>
    <li>Major museums often close one day per week (commonly Monday)</li>
    <li>It's better to book tickets online in advance for popular attractions like the Colosseum or the Vatican Museums</li>
    <li>Photography policies vary by location - always check before taking photos, especially inside churches or museums</li>
    <li>Appropriate dress is required when visiting religious sites (covered shoulders and knees)</li>
</ul>

