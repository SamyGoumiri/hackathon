<h2>Frasi Utili per Viaggiare</h2>
<ul>
    <li><span class="italian-word">Vorrei un biglietto per...</span> (vor-ray oon bee-lyet-toh per) - I would like a ticket to...</li>
    <li><span class="italian-word">A che ora parte il treno/autobus?</span> (ah keh oh-rah par-teh eel tray-no/ow-toh-boos) - What time does the train/bus leave?</li>
    <li><span class="italian-word">Dov'è la stazione/fermata di...?</span> (doh-veh lah stah-tzee-oh-neh/fer-mah-tah dee) - Where is the station/stop for...?</li>
    <li><span class="italian-word">Vorrei noleggiare una macchina.</span> (vor-ray no-led-jah-reh oo-nah mak-kee-nah) - I would like to rent a car.</li>
</ul>

<div class="example">
    <div class="example-title">Esempio di Conversazione</div>
    <p>
        <strong>Passeggero:</strong> Buongiorno, vorrei un biglietto di sola andata per Bologna, per favore.<br>
        <strong>Bigliettaio:</strong> Buongiorno. Per oggi?<br>
        <strong>Passeggero:</strong> Sì, per il treno delle 14:30.<br>
        <strong>Bigliettaio:</strong> Va bene. Sono 45 euro.<br>
        <strong>Passeggero:</strong> Ecco. Il treno parte dal binario 3?<br>
        <strong>Bigliettaio:</strong> No, parte dal binario 5. Ecco il suo biglietto. Buon viaggio!<br>
        <strong>Passeggero:</strong> Grazie mille!
    </p>
</div>

<h2>Problemi Comuni con i Trasporti</h2>
<ul>
    <li><span class="italian-word">Il treno/autobus è in ritardo.</span> - The train/bus is late.</li>
    <li><span class="italian-word">Il volo è cancellato.</span> - The flight is canceled.</li>
    <li><span class="italian-word">Ho perso il mio treno/autobus.</span> - I missed my train/bus.</li>
    <li><span class="italian-word">Dove posso comprare un biglietto?</span> - Where can I buy a ticket?</li>
    <li><span class="italian-word">Posso prenotare online?</span> - Can I book online?</li>
</ul>

