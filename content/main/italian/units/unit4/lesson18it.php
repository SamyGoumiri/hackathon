<h2>Prenotare una Camera</h2>
<ul>
    <li><span class="italian-word">Vorrei prenotare una camera.</span> (vor-ray preh-no-tah-reh oo-nah kah-meh-rah) - I would like to book a room.</li>
    <li><span class="italian-word">Per quante notti?</span> (per kwan-teh not-tee) - For how many nights?</li>
    <li><span class="italian-word">Dal [data] al [data].</span> (dal [data] al [data]) - From [date] to [date].</li>
    <li><span class="italian-word">Avete una camera disponibile?</span> (ah-veh-teh oo-nah kah-meh-rah dee-spo-nee-bee-leh) - Do you have a room available?</li>
    <li><span class="italian-word">Qual è il prezzo per notte?</span> (kwahl eh eel pret-tso per not-teh) - What's the price per night?</li>
    <li><span class="italian-word">La colazione è inclusa?</span> (lah ko-la-tzee-oh-neh eh een-kloo-sah) - Is breakfast included?</li>
</ul>

<h2>Al Check-in/Check-out</h2>
<ul>
    <li><span class="italian-word">Ho una prenotazione a nome di...</span> (oh oo-nah preh-no-ta-tzee-oh-neh ah no-meh dee) - I have a reservation under the name...</li>
    <li><span class="italian-word">A che ora è il check-out?</span> (ah keh o-rah eh eel check-out) - What time is check-out?</li>
    <li><span class="italian-word">Vorrei prolungare il mio soggiorno.</span> (vor-ray pro-loon-gah-reh eel mee-o sod-jor-no) - I would like to extend my stay.</li>
    <li><span class="italian-word">Vorrei il conto, per favore.</span> (vor-ray eel kon-toh, per fah-vo-reh) - I would like the bill, please.</li>
    <li><span class="italian-word">C'è una cassaforte in camera?</span> (cheh oo-nah kas-sah-for-teh een kah-meh-rah) - Is there a safe in the room?</li>
    <li><span class="italian-word">Come posso accedere al Wi-Fi?</span> (ko-meh pos-so ak-che-deh-reh al wee-fee) - How can I access the Wi-Fi?</li>
</ul>

<div class="example">
    <div class="example-title">Esempio di Conversazione - Fare una Prenotazione</div>
    <p>
        <strong>Ospite:</strong> Buongiorno, vorrei prenotare una camera per due persone, per favore.<br>
        <strong>Receptionist:</strong> Buongiorno. Per quali date?<br>
        <strong>Ospite:</strong> Dal 15 al 18 giugno.<br>
        <strong>Receptionist:</strong> Benissimo. Abbiamo una camera matrimoniale disponibile per queste date. Costa 95 euro a notte.<br>
        <strong>Ospite:</strong> La colazione è inclusa?<br>
        <strong>Receptionist:</strong> No, la colazione costa 12 euro a persona.<br>
        <strong>Ospite:</strong> Va bene, prendo la camera. C'è il Wi-Fi?<br>
        <strong>Receptionist:</strong> Sì, il Wi-Fi è gratuito in tutto l'albergo. Posso avere il suo nome, per favore?<br>
        <strong>Ospite:</strong> Mi chiamo Paolo Bianchi.
    </p>
</div>

