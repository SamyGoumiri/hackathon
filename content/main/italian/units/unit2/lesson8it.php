<h2>Minutes Before the Hour</h2>
<p>To express minutes before the next hour, you can use "meno":</p>

<table class="vocabulary-table">
    <tr>
        <th>Italian</th>
        <th>Pronunciation</th>
        <th>English</th>
    </tr>
    <tr>
        <td class="italian-word">Sono le sette meno cinque</td>
        <td class="pronunciation">soh-noh leh set-teh meh-noh cheen-kweh</td>
        <td>It's 6:55 (5 minutes to 7)</td>
    </tr>
    <tr>
        <td class="italian-word">Sono le otto meno dieci</td>
        <td class="pronunciation">soh-noh leh ot-toh meh-noh dee-eh-chee</td>
        <td>It's 7:50 (10 minutes to 8)</td>
    </tr>
    <tr>
        <td class="italian-word">Sono le nove meno un quarto</td>
        <td class="pronunciation">soh-noh leh noh-veh meh-noh oon kwar-toh</td>
        <td>It's 8:45 (quarter to 9)</td>
    </tr>
    <tr>
        <td class="italian-word">Sono le dieci meno venti</td>
        <td class="pronunciation">soh-noh leh dee-eh-chee meh-noh vehn-tee</td>
        <td>It's 9:40 (20 minutes to 10)</td>
    </tr>
</table>

