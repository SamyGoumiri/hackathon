<h2>Telling the Hour</h2>
<p>To tell the hour in Italian, use "Sono le" followed by the number and "ora/ore" (except for 1 o'clock):</p>

<table class="vocabulary-table">
    <tr>
        <th>Italian</th>
        <th>Pronunciation</th>
        <th>English</th>
    </tr>
    <tr>
        <td class="italian-word">È l'una</td>
        <td class="pronunciation">eh loo-nah</td>
        <td>It's 1 o'clock</td>
    </tr>
    <tr>
        <td class="italian-word">Sono le due</td>
        <td class="pronunciation">soh-noh leh doo-eh</td>
        <td>It's 2 o'clock</td>
    </tr>
    <tr>
        <td class="italian-word">Sono le tre</td>
        <td class="pronunciation">soh-noh leh treh</td>
        <td>It's 3 o'clock</td>
    </tr>
    <tr>
        <td class="italian-word">È mezzogiorno</td>
        <td class="pronunciation">eh med-zoh-jor-noh</td>
        <td>It's noon (12 PM)</td>
    </tr>
    <tr>
        <td class="italian-word">È mezzanotte</td>
        <td class="pronunciation">eh med-zah-not-teh</td>
        <td>It's midnight (12 AM)</td>
    </tr>
</table>

