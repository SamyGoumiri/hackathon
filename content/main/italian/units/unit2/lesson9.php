<p>In this lesson, you'll learn the days of the week, months of the year, and how to talk about dates in Italian.</p>

<h2>Days of the Week</h2>
<p>In Italian, the days of the week are masculine (except for "domenica") and are not capitalized. The week typically begins with Monday (lunedì).</p>

