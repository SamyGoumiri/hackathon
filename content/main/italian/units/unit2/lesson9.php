<h2>Expressing Dates</h2>
<p>In Italian, dates are typically written and pronounced in the format "il + day number + month".</p>

<table class="vocabulary-table">
    <tr>
        <th>Italian</th>
        <th>Pronunciation</th>
        <th>English</th>
    </tr>
    <tr>
        <td class="italian-word">Qual è la data di oggi?</td>
        <td class="pronunciation">kwahl eh lah dah-tah dee ohd-jee</td>
        <td>What's the date today?</td>
    </tr>
    <tr>
        <td class="italian-word">Oggi è il...</td>
        <td class="pronunciation">ohd-jee eh eel</td>
        <td>Today is the...</td>
    </tr>
    <tr>
        <td class="italian-word">il primo gennaio</td>
        <td class="pronunciation">eel pree-moh jehn-nah-yoh</td>
        <td>January 1st</td>
    </tr>
    <tr>
        <td class="italian-word">il due febbraio</td>
        <td class="pronunciation">eel doo-eh fehb-brah-yoh</td>
        <td>February 2nd</td>
    </tr>
    <tr>
        <td class="italian-word">il quindici marzo</td>
        <td class="pronunciation">eel kween-dee-chee mahr-tsoh</td>
        <td>March 15th</td>
    </tr>
    <tr>
        <td class="italian-word">il trenta aprile</td>
        <td class="pronunciation">eel trehn-tah ah-pree-leh</td>
        <td>April 30th</td>
    </tr>
</table>

