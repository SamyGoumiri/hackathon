<div class="example">
    <div class="example-title">Examples</div>
    <p>
        <strong>Sono le due e un quarto</strong> - It's quarter past two (2:15)<br>
        <strong>È l'una e mezzo</strong> - It's half past one (1:30)<br>
        <strong>Sono le tre e tre quarti</strong> - It's three quarters past three (3:45)<br>
        <strong>Sono le quattro meno un quarto</strong> - It's quarter to four (3:45)<br>
        <strong>Sono le sei meno dieci</strong> - It's ten to six (5:50)
    </p>
</div>

<h2>AM and PM</h2>
<p>Italian uses a 24-hour clock system, but you can also express morning, afternoon, evening and night:</p>

<table class="vocabulary-table">
    <tr>
        <th>Italian</th>
        <th>Pronunciation</th>
        <th>English</th>
    </tr>
    <tr>
        <td class="italian-word">di mattina</td>
        <td class="pronunciation">dee maht-tee-nah</td>
        <td>in the morning</td>
    </tr>
    <tr>
        <td class="italian-word">del pomeriggio</td>
        <td class="pronunciation">dehl poh-meh-reed-joh</td>
        <td>in the afternoon</td>
    </tr>
    <tr>
        <td class="italian-word">di sera</td>
        <td class="pronunciation">dee seh-rah</td>
        <td>in the evening</td>
    </tr>
    <tr>
        <td class="italian-word">di notte</td>
        <td class="pronunciation">dee noht-teh</td>
        <td>at night</td>
    </tr>
</table>

<div class="example">
    <div class="example-title">Examples</div>
    <p>
        <strong>Sono le nove di mattina</strong> - It's nine in the morning (9:00 AM)<br>
        <strong>Sono le due del pomeriggio</strong> - It's two in the afternoon (2:00 PM)<br>
        <strong>Sono le otto di sera</strong> - It's eight in the evening (8:00 PM)<br>
        <strong>È l'una di notte</strong> - It's one at night (1:00 AM)
    </p>
</div>

