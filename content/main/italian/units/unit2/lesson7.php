<div class="example">
    <div class="example-title">Example Sentences</div>
    <p>
        <strong>Regular -ARE verb:</strong> Io lavoro a Roma. (I work in Rome.)<br>
        <strong>Regular -ERE verb:</strong> Noi leggiamo un libro. (We are reading a book.)<br>
        <strong>Regular -IRE verb:</strong> Loro dormono alle dieci. (They sleep at ten.)<br>
        <strong>Essere:</strong> Io sono italiano. (I am Italian.)<br>
        <strong>Avere:</strong> Tu hai una bella macchina. (You have a beautiful car.)<br>
        <strong>Fare:</strong> Lei fa i compiti. (She is doing her homework.)<br>
        <strong>Andare:</strong> Noi andiamo al cinema. (We are going to the cinema.)
    </p>
</div>

