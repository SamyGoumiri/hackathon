<p>In this lesson, you'll learn how to conjugate and use common verbs in the present tense in Italian.</p>

<h2>Regular Verbs (-ARE)</h2>
<p>Most Italian verbs end in -are. Here's how to conjugate them in present tense:</p>

<table class="vocabulary-table">
    <tr>
        <th>Subject</th>
        <th>Ending</th>
        <th>Example: Parlare (to speak)</th>
    </tr>
    <tr>
        <td class="italian-word">io (I)</td>
        <td class="pronunciation">-o</td>
        <td>io parlo</td>
    </tr>
    <tr>
        <td class="italian-word">tu (you, informal)</td>
        <td class="pronunciation">-i</td>
        <td>tu parli</td>
    </tr>
    <tr>
        <td class="italian-word">lui/lei/Lei (he/she/you formal)</td>
        <td class="pronunciation">-a</td>
        <td>lui/lei/Lei parla</td>
    </tr>
    <tr>
        <td class="italian-word">noi (we)</td>
        <td class="pronunciation">-iamo</td>
        <td>noi parliamo</td>
    </tr>
    <tr>
        <td class="italian-word">voi (you plural)</td>
        <td class="pronunciation">-ate</td>
        <td>voi parlate</td>
    </tr>
    <tr>
        <td class="italian-word">loro (they)</td>
        <td class="pronunciation">-ano</td>
        <td>loro parlano</td>
    </tr>
</table>

