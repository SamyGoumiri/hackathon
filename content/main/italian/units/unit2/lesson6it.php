        <strong>Durante il giorno,</strong> vado al lavoro alle 8. Lavoro fino a mezzogiorno, poi pranzo. Lavoro ancora nel pomeriggio e torno a casa alle 18.<br><br>
        <strong>La sera,</strong> preparo la cena e mangio verso le 19. Dopo cena, guardo la TV o leggo un libro. Vado a letto verso le 23.
    </p>
