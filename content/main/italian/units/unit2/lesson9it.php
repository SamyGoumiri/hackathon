<h2>Expressing Dates</h2>
<p>In Italian, dates are typically written and pronounced in the format "il + day number + month".</p>

<table class="vocabulary-table">
    <tr>
        <th>Italian</th>
        <th>Pronunciation</th>
        <th>English</th>
    </tr>
    <tr>
        <td class="italian-word">Qual è la data di oggi?</td>
        <td class="pronunciation">kwahl eh lah dah-tah dee od-jee</td>
        <td>What's the date today?</td>
    </tr>
    <tr>
        <td class="italian-word">Oggi è il...</td>
        <td class="pronunciation">od-jee eh eel</td>
        <td>Today is the...</td>
    </tr>
    <tr>
        <td class="italian-word">il primo gennaio</td>
        <td class="pronunciation">eel pree-moh jen-nah-yoh</td>
        <td>January 1st</td>
    </tr>
    <tr>
        <td class="italian-word">il due febbraio</td>
        <td class="pronunciation">eel doo-eh feb-brah-yoh</td>
        <td>February 2nd</td>
    </tr>
    <tr>
        <td class="italian-word">il quindici marzo</td>
