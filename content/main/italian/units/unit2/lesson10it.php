<div class="example">
    <div class="example-title">Example Conversations</div>
    <p>
        <strong>Conversation 1:</strong><br>
        <strong>Person A:</strong> Che tempo fa oggi?<br>
        <strong>Person B:</strong> Fa bel tempo e caldo. C'è il sole e ci sono alcune nuvole.<br>
        <strong>Person A:</strong> Qual è la temperatura?<br>
        <strong>Person B:</strong> Ci sono 25 gradi.<br>
        <strong>Person A:</strong> È perfetto per andare in spiaggia!
    </p>
    <p>
        <strong>Conversation 2:</strong><br>
        <strong>Person A:</strong> Che tempo farà a Roma questo fine settimana?<br>
        <strong>Person B:</strong> Secondo le previsioni, pioverà sabato e sarà nuvoloso domenica.<br>
        <strong>Person A:</strong> Che temperatura ci sarà?<br>
        <strong>Person B:</strong> Ci saranno circa 15 gradi. Farà abbastanza fresco.<br>
