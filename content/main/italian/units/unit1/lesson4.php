<h2>Forming Questions</h2>
<p>There are several ways to form questions in Italian:</p>

<h3>1. Intonation</h3>
<p>Simply raise the pitch of your voice at the end of a statement:</p>
<ul>
    <li><span class="italian-word">Parli italiano.</span> (You speak Italian.) - Statement</li>
    <li><span class="italian-word">Parli italiano?</span> (Do you speak Italian?) - Question</li>
</ul>

<h3>2. Question Words</h3>
<p>Place a question word at the beginning of a sentence:</p>
<ul>
    <li><span class="italian-word">Dove abiti?</span> (Where do you live?)</li>
    <li><span class="italian-word">Come ti chiami?</span> (What's your name?)</li>
</ul>

<h3>3. Verb First</h3>
<p>In some cases, especially with the verb "essere" (to be), you can place the verb first:</p>
<ul>
    <li><span class="italian-word">Sei italiano?</span> (Are you Italian?)</li>
    <li><span class="italian-word">Hai una penna?</span> (Do you have a pen?)</li>
</ul>

