<h2>Special Consonants</h2>
<p>Some Italian consonants can be challenging for English speakers:</p>

<ul>
    <li><span class="italian-word">C + e, i</span> - Pronounced like "ch" in "cheese" (cena, ciao)</li>
    <li><span class="italian-word">C + a, o, u</span> - Pronounced like "k" (casa, cosa)</li>
    <li><span class="italian-word">G + e, i</span> - Pronounced like "j" in "judge" (gente, giorno)</li>
    <li><span class="italian-word">G + a, o, u</span> - Hard "g" like in "gate" (gatto, agosto)</li>
    <li><span class="italian-word">Gli</span> - Similar to "lli" in "million" (famiglia)</li>
    <li><span class="italian-word">Gn</span> - Like "ny" in "canyon" (gnocchi)</li>
</ul>

