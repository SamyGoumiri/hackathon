<h2>Stress</h2>
<p>In most Italian words, the stress falls on the second-to-last syllable:</p>
<ul>
    <li>ge-LA-to (ice cream)</li>
    <li>ra-GAZ-zo (boy)</li>
    <li>a-MI-co (friend)</li>
</ul>
