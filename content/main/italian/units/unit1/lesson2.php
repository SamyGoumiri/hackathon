<h2>Consonants</h2>
<p>Most Italian consonants are similar to English, but here are some important differences:</p>

<table class="vocabulary-table">
    <tr>
        <th>Sound</th>
        <th>Pronunciation</th>
        <th>Example</th>
    </tr>
    <tr>
        <td class="italian-word">c + a, o, u</td>
        <td class="pronunciation">k</td>
        <td>casa (house)</td>
    </tr>
    <tr>
        <td class="italian-word">c + i, e</td>
        <td class="pronunciation">ch (as in "cheese")</td>
        <td>ciao (hello)</td>
    </tr>
    <tr>
        <td class="italian-word">g + a, o, u</td>
        <td class="pronunciation">g (as in "go")</td>
        <td>gatto (cat)</td>
    </tr>
    <tr>
        <td class="italian-word">g + i, e</td>
        <td class="pronunciation">j (as in "jet")</td>
        <td>gelato (ice cream)</td>
    </tr>
    <tr>
        <td class="italian-word">gn</td>
        <td class="pronunciation">ny (as in "canyon")</td>
        <td>gnocchi</td>
    </tr>
</table>

<h2>Double Consonants</h2>
<p>In Italian, double consonants are pronounced longer and with more emphasis than single consonants:</p>

<ul>
    <li><span class="italian-word">penna</span> (pen-na) - pen</li>
    <li><span class="italian-word">anno</span> (an-no) - year</li>
    <li><span class="italian-word">azzurro</span> (ad-zur-ro) - blue</li>
</ul>

