<h2>Introducing Yourself</h2>
<p>To introduce yourself in Italian, you can use these phrases:</p>

<ul>
    <li><span class="italian-word">Mi chiamo...</span> (mee kya-moh) - My name is...</li>
    <li><span class="italian-word">Sono...</span> (soh-noh) - I am...</li>
    <li><span class="italian-word">Piacere</span> (pyah-cheh-reh) - Nice to meet you</li>
</ul>

<div class="example">
    <div class="example-title">Example Conversation</div>
    <p>
        <strong>Person A:</strong> Buongiorno! Mi chiamo Maria.<br>
        <strong>Person B:</strong> Buongiorno Maria! Mi chiamo Paolo. Piacere!<br>
        <strong>Person A:</strong> Piacere, Paolo!
    </p>
</div>

<h2>Practice</h2>
<p>Try introducing yourself in Italian. Complete these phrases:</p>
<ul>
    <li>Buongiorno! Mi chiamo _______.</li>
    <li>Sono _______. (add your nationality or profession)</li>
</ul>

<h2>Key Points to Remember</h2>
<ul>
    <li>Use "Buongiorno" during the morning/day and "Buonasera" in the evening.</li>
    <li>"Ciao" is informal and should only be used with friends and family.</li>
    <li>"Piacere" is used when meeting someone for the first time.</li>
</ul>
