<h2>Forming Questions</h2>
<p>There are two main ways to form questions in Italian:</p>

<h3>1. Intonation</h3>
<p>Simply raise the pitch of your voice at the end of a statement:</p>
<ul>
    <li><span class="italian-word">Tu parli italiano.</span> (You speak Italian.) - Statement</li>
    <li><span class="italian-word">Tu parli italiano?</span> (Do you speak Italian?) - Question</li>
</ul>

<h3>2. Question Words</h3>
<p>Place the question word at the beginning of the sentence:</p>
<ul>
    <li><span class="italian-word">Dove abiti?</span> (Where do you live?)</li>
    <li><span class="italian-word">Come stai?</span> (How are you?)</li>
</ul>

<div class="example">
    <div class="example-title">Example Questions</div>
    <p>
        <strong>Come ti chiami?</strong> (What's your name?)<br>
        <strong>Di dove sei?</strong> (Where are you from?)<br>
        <strong>Ti piace la musica?</strong> (Do you like music?)<br>
        <strong>Quanti anni hai?</strong> (How old are you?)
    </p>
</div>

