<h2>Cultural Note</h2>
<p>In Italy, it's considered very important to say "Buongiorno" (Good day) or "Buonasera" (Good evening) when entering a shop or restaurant, and "Arrivederci" (Goodbye) when leaving. Not doing so is considered impolite. Italians also appreciate when visitors attempt to speak their language, even if just using basic phrases.</p>
